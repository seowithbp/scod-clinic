        ];
        let videoIndex = 0;
        let galleryIndex = 0;
        function renderVideos() {
            const track = document.getElementById('video-track');
            track.innerHTML = awarenessVideos.map(v => `
                <div class="w-full lg:w-1/2 flex-shrink-0 px-2">
                    <div class="relative rounded-xl overflow-hidden aspect-video cursor-pointer group" onclick="openModal('${v.videoId}')">
                        <img src="${v.thumbnail}" alt="${v.title}" class="w-full h-full object-cover">
                        <div class="absolute inset-0 bg-black/30 flex items-center justify-center group-hover:bg-black/20 transition-colors">
                            <i data-feather="play" class="w-12 h-12 text-white"></i>
                        </div>
                    </div>
                </div>
            `).join('');
            feather.replace();
        }
        function renderGallery() {
            const track = document.getElementById('gallery-track');
            track.innerHTML = galleryImages.map(img => `
                <div class="w-full lg:w-1/3 flex-shrink-0 px-2">
                    <div class="relative rounded-2xl overflow-hidden h-80">
                        <img src="${img.src}" alt="${img.caption}" class="w-full h-full object-cover">
                        <div class="absolute bottom-0 left-0 right-0 p-6 bg-gradient-to-t from-black/90 to-transparent">
                            <p class="text-emerald-400 text-xs font-bold uppercase mb-1">${img.desc}</p>
                            <h3 class="text-xl font-bold">${img.caption}</h3>
                        </div>
                    </div>
                </div>
            `).join('');
        }
        function updateSlider(trackId, index, itemsPerView) {
            const track = document.getElementById(trackId);
            const percentage = index * (100 / itemsPerView);
            track.style.transform = `translateX(-${percentage}%)`;
        }
        function nextVideo() {
            const itemsPerView = window.innerWidth >= 1024 ? 2 : 1;
            if (videoIndex < awarenessVideos.length - itemsPerView) videoIndex++;
            else videoIndex = 0;
            updateSlider('video-track', videoIndex, window.innerWidth >= 1024 ? 2 : 1);
        }
        function prevVideo() {
            const itemsPerView = window.innerWidth >= 1024 ? 2 : 1;
            if (videoIndex > 0) videoIndex--;
            else videoIndex = awarenessVideos.length - itemsPerView;
            updateSlider('video-track', videoIndex, window.innerWidth >= 1024 ? 2 : 1);
        }
        function nextGallery() {
            const itemsPerView = window.innerWidth >= 1024 ? 3 : 1;
            if (galleryIndex < galleryImages.length - itemsPerView) galleryIndex++;
            else galleryIndex = 0;
            updateSlider('gallery-track', galleryIndex, itemsPerView);
        }
        function prevGallery() {
            const itemsPerView = window.innerWidth >= 1024 ? 3 : 1;
            if (galleryIndex > 0) galleryIndex--;
            else galleryIndex = galleryImages.length - itemsPerView;
            updateSlider('gallery-track', galleryIndex, itemsPerView);
        }
        function openModal(videoId) {
            document.getElementById('modal-iframe').src = `https://www.youtube.com/embed/${videoId}?autoplay=1`;
            document.getElementById('video-modal').classList.remove('hidden');
        }
        function closeModal() {
            document.getElementById('video-modal').classList.add('hidden');
            document.getElementById('modal-iframe').src = '';
        }
        renderVideos();
        renderGallery();
    </script>
