                        <h3 class="text-lg font-bold text-gray-900 mb-2">2. Prioritize Protein Intake</h3>
                        <p class="text-gray-600 text-sm">
                            Aim for 60 to 80 grams of protein daily. Protein is crucial for muscle preservation, wound healing, metabolic speed, and preventing hair thinning during initial rapid weight loss phases. Lean meats, eggs, paneer, tofu, lentils, and whey protein isolates are excellent choices.
                        </p>
                    </div>

                    <div class="bg-gray-50 rounded-xl p-6 border border-gray-200">
                        <h3 class="text-lg font-bold text-gray-900 mb-2">3. Master the Fluid Separation Rule</h3>
                        <p class="text-gray-600 text-sm">
                            Drink 1.5 to 2 liters of water daily to remain hydrated, but <strong>never drink water while eating</strong>. Stop drinking liquids 30 minutes before meals and wait 30 minutes after eating before drinking again. Drinking during meals flushes food out of the pouch too quickly, causing premature hunger.
                        </p>
                    </div>

                    <div class="bg-gray-50 rounded-xl p-6 border border-gray-200">
                        <h3 class="text-lg font-bold text-gray-900 mb-2">4. Lifelong Vitamin Supplementation</h3>
                        <p class="text-gray-600 text-sm">
                            Take prescribed bariatric multivitamins, calcium citrate with Vitamin D, iron, and sublingual Vitamin B12 every day without fail. Regular blood tests every 3 to 6 months will monitor your nutrient levels.
                        </p>
                    </div>

                    <div class="bg-gray-50 rounded-xl p-6 border border-gray-200">
                        <h3 class="text-lg font-bold text-gray-900 mb-2">5. Mindful Eating Habits</h3>
                        <p class="text-gray-600 text-sm">
                            Take very small bites, chew each mouthful 20 to 30 times until liquid consistency, and eat slowly over 20 to 30 minutes. Stop eating immediately when you feel a sense of fullness or pressure behind your breastbone.
                        </p>
                    </div>

                    <div class="bg-gray-50 rounded-xl p-6 border border-gray-200">
                        <h3 class="text-lg font-bold text-gray-900 mb-2">6. Regular Exercise & Activity</h3>
                        <p class="text-gray-600 text-sm">
                            Start walking short distances on your very first day after surgery to prevent blood clots. Gradually increase to 30 minutes of daily brisk walking by week 3, and incorporate light resistance training after 6 to 8 weeks with your surgeon's clearance.
