                <h2 class="text-2xl font-bold text-gray-900 mt-8 mb-4">Understanding Weight Loss</h2>

                <p class="text-gray-600 mb-6">
                    To accurately gauge your transformation, it is essential to understand the biological mechanisms of post-bariatric weight loss, as well as how bariatric specialists calculate progress. Weight loss after bariatric surgery occurs through three primary mechanisms:
                </p>

                <ul class="list-disc list-inside text-gray-600 mb-6 space-y-2">
                    <li><strong>Gastric Restriction:</strong> Reducing the capacity of the stomach limits the volume of food you can comfortably consume in one sitting, promoting early satiety (fullness).</li>
                    <li><strong>Hormonal Modulation:</strong> Procedures like sleeve gastrectomy remove the portion of the stomach that produces <em>ghrelin</em> (the primary hunger hormone). Meanwhile, gut hormones like GLP-1 and PYY increase, curbing cravings and resetting metabolic setpoints.</li>
                    <li><strong>Nutritional Malabsorption:</strong> Certain procedures, such as Roux-en-Y Gastric Bypass or Mini Gastric Bypass, reroute a small segment of the small intestine, slightly decreasing calorie and fat absorption.</li>
                </ul>

                <h3 class="text-xl font-bold text-gray-900 mt-6 mb-3">Total Weight Loss vs. Excess Weight Loss</h3>

                <p class="text-gray-600 mb-6">
                    When medical experts discuss <strong>average weight loss after bariatric surgery</strong>, they usually refer to <em>Excess Weight Loss (%EWL)</em> rather than Total Weight Loss (%TWL). Understanding this distinction helps you calculate your personal weight loss goal accurately:
                </p>

                <div class="bg-gray-50 border border-gray-200 rounded-xl p-6 mb-6">
                    <h4 class="font-bold text-gray-900 mb-3">How to Calculate Your Excess Weight:</h4>
                    <p class="text-gray-600 text-sm mb-2"><strong>Ideal Weight:</strong> Based on a healthy Body Mass Index (BMI of 25 kg/m² for your height).</p>
                    <p class="text-gray-600 text-sm mb-2"><strong>Excess Weight:</strong> Current Total Weight minus Ideal Healthy Weight.</p>
                    <p class="text-gray-600 text-sm"><strong>Example:</strong> If your current weight is 120 kg and your ideal healthy weight for your height is 70 kg, your excess weight is 50 kg. Losing 70% of your excess weight means shedding 35 kg, bringing your final weight down to 85 kg.</p>
                </div>

