                        <p class="text-gray-600 text-sm">
                            Transition through dietary phases slowly: Clear liquids (Days 1–7) &rarr; Full liquids & protein shakes (Weeks 2–3) &rarr; Pureed foods (Weeks 4–5) &rarr; Soft solids (Weeks 6–8) &rarr; Normal healthy solids. Introducing hard solids too early can strain staple lines and cause severe vomiting.
                        </p>
