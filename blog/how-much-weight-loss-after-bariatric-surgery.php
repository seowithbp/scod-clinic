                <h2 class="text-2xl font-bold text-gray-900 mt-8 mb-4">Risks Associated with Bariatric Surgery Procedures</h2>

                <p class="text-gray-600 mb-6">
                    Modern bariatric surgery is performed using advanced laparoscopic and robotic minimally invasive techniques. Because of these advances, the overall safety profile of bariatric surgery is comparable to routine procedures like gallbladder removal or knee replacement. However, as with any major surgical procedure, it is vital to be fully informed regarding potential risks and complications.
                </p>

                <h3 class="text-xl font-bold text-gray-900 mt-6 mb-3">Short-Term Post-Operative Risks</h3>
                <ul class="list-disc list-inside text-gray-600 mb-6 space-y-2">
                    <li><strong>Staple Line Leaks or Bleeding:</strong> Rare complications (under 1%) involving fluid leakage along the stomach cut line, which is minimized by utilizing premium surgical staplers and reinforcement techniques.</li>
                    <li><strong>Infection at Incision Sites:</strong> Minor skin infections at the small keyhole ports, easily manageable with antibiotics.</li>
                    <li><strong>Deep Vein Thrombosis (DVT):</strong> Blood clots in the legs triggered by immobility, which are prevented with blood-thinning injections and early post-op walking.</li>
                    <li><strong>Anesthesia Reactions:</strong> Temporary groggy feelings or respiratory irritation managed by experienced anesthesiologists.</li>
                </ul>

                <h3 class="text-xl font-bold text-gray-900 mt-6 mb-3">Long-Term Considerations & Complications</h3>
                <ul class="list-disc list-inside text-gray-600 mb-6 space-y-2">
                    <li><strong>Nutritional & Vitamin Deficiencies:</strong> Reduced stomach size and intestinal absorption can lead to lower levels of Iron, Vitamin B12, Calcium, and Vitamin D if daily supplements are neglected.</li>
                    <li><strong>Dumping Syndrome:</strong> Occurs primarily after gastric bypass when high-sugar or high-fat foods enter the small intestine too quickly, causing nausea, sweating, and dizziness.</li>
                    <li><strong>Gallstone Formation:</strong> Rapid breakdown of body fat can cause cholesterol crystallization in the gallbladder. Doctors often prescribe preventive medications for the first six months.</li>
                    <li><strong>Excess Sagging Skin:</strong> Following substantial fat loss, loose skin may develop on the abdomen, arms, and thighs. Skin elasticity depends on age and genetics; body contouring procedures can address this later if desired.</li>
                </ul>

