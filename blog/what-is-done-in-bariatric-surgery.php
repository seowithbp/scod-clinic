                <p class="text-lg text-gray-800 leading-relaxed font-normal">
                    For individuals battling severe obesity and metabolic conditions, conventional diet plans and medications frequently reach a biological ceiling. When standard approaches fail to produce lasting weight relief, metabolic surgery stands out as the most reliable, evidence-based treatment. Yet, one question naturally arises before a consultation: <em>What is done in bariatric surgery?</em>
                </p>

                <p>
                    Rather than an invasive open operation requiring painful incisions and weeks of bed rest, modern bariatric care is a minimally invasive science. In 2026, operations rely on ultra-high-definition 4K optics, robotic assistance, smart tissue staplers, and advanced metabolic principles.
                </p>

                <p>
                    According to <a href="https://scodclinic.com/about" class="text-scod hover:text-blue-700 font-semibold underline decoration-scod/40">Dr. Arush Sabharwal</a>, Chief Metabolic and Bariatric Surgeon at SCOD Clinic, understanding the surgical steps demystifies the experience, relieves apprehension, and prepares patients for lasting physical transformation.
                </p>

                <!-- Section 1 -->
                <h2 id="understanding-bariatric-surgery" class="text-2xl md:text-3xl font-bold text-gray-900 mt-10 mb-4 pt-4 border-t border-gray-100">
                    Understanding Bariatric Surgery
                </h2>

                <p>
                    While physical volume reduction is an important factor, clinical science confirms that <a href="https://en.wikipedia.org/wiki/Bariatric_surgery" target="_blank" rel="noopener noreferrer" class="text-scod hover:text-blue-700 font-semibold underline decoration-scod/40">bariatric surgery</a> operates primarily as an endocrine and metabolic intervention.
                </p>

                <p>
                    The human digestive tract is the body’s largest hormone-producing organ. Every meal triggers chemical messengers that signal hunger, satiety, or fat storage. In individuals with chronic obesity, the hormonal set-point defends an elevated weight. Metabolic surgery resets this internal biological thermostat. By modifying the digestive tract, surgeons rewire the chemical signals connecting the stomach, intestines, liver, and brain to support lasting weight loss.
                </p>

                <!-- Section 2 -->
                <h2 id="preoperative-workup" class="text-2xl md:text-3xl font-bold text-gray-900 mt-10 mb-4 pt-4 border-t border-gray-100">
                    What Happens Before the Operation: The Pre-Surgical Preparation
                </h2>

                <p>
                    The surgical procedure itself is one step within a structured clinical roadmap. Before entering the operating room, patients complete comprehensive evaluations to ensure complete clinical safety:
                </p>

                <ul class="list-disc pl-6 space-y-2 text-gray-700">
                    <li>Cardiopulmonary Clearance: Blood work, ECG, and imaging verify that the heart and lungs safely tolerate anesthesia.</li>
                    <li>Endoscopic Assessment: An upper endoscopy checks the stomach lining and rules out hiatal hernias or active infections.</li>
                    <li>Nutritional Profiling: Baseline checks of vitamin D, B12, iron, and blood glucose correct deficiencies before admission.</li>
                    <li>Liver Shrinkage Diet: A 10 to 14 day high-protein, low-carb plan reduces liver volume for clear surgical visibility.</li>
                </ul>

                <!-- Section 3 -->
                <h2 id="step-by-step-theatre" class="text-2xl md:text-3xl font-bold text-gray-900 mt-10 mb-4 pt-4 border-t border-gray-100">
                    Step-by-Step Breakdown: Inside the Operation Theatre
                </h2>

                <p>
                    Here is what takes place inside the operating suite during a modern bariatric procedure:
                </p>

                <h3 class="text-xl font-bold text-gray-900 mt-6 mb-2">Step 1: General Anesthesia</h3>
                <p>
                    The anesthesia team administers gentle intravenous medications and oxygen, allowing the patient to enter a restful sleep without discomfort. Continuous monitors track vital signs throughout the entire procedure.
                </p>

                <h3 class="text-xl font-bold text-gray-900 mt-6 mb-2">Step 2: Keyhole Port Creation</h3>
                <p>
                    The surgeon creates four or five tiny keyhole incisions, each measuring 5 to 12 millimeters. Carbon dioxide gas is gently introduced into the abdomen to expand the workspace and protect delicate tissues.
                </p>

                <h3 class="text-xl font-bold text-gray-900 mt-6 mb-2">Step 3: High-Definition Visualization</h3>
                <p>
                    A laparoscope with a 4K camera and cold light source is positioned through one of the ports. The surgical team views internal organs on high-resolution screens with ten-fold magnification.
                </p>

                <h3 class="text-xl font-bold text-gray-900 mt-6 mb-2">Step 4: Remodeling the Stomach and Digestive Tract</h3>
                <p>
                    Using specialized ultrasonic energy devices, the surgeon mobilizes the stomach. The planned remodeling is carried out using motorized surgical staplers that cut and seal tissues with microscopic precision.
                </p>

                <h3 class="text-xl font-bold text-gray-900 mt-6 mb-2">Step 5: Intraoperative Leak Testing</h3>
                <p>
                    Before finishing the procedure, the integrity of all connections is confirmed using an intraoperative air-leak test or blue dye test under sterile saline to verify that every staple line is airtight and watertight.
                </p>

                <h3 class="text-xl font-bold text-gray-900 mt-6 mb-2">Step 6: Gas Release and Skin Closure</h3>
                <p>
                    Instruments are removed, and carbon dioxide gas is thoroughly vented from the abdomen. The tiny skin incisions are closed using dissolvable sub-cuticular sutures and covered with water-resistant dressings.
                </p>

                <!-- Section 4 -->
                <h2 id="common-procedures-compared" class="text-2xl md:text-3xl font-bold text-gray-900 mt-10 mb-4 pt-4 border-t border-gray-100">
                    Common Procedures: Sleeve Gastrectomy vs. Gastric Bypass vs. OAGB
                </h2>

                <p>
                    Depending on an individual patient’s medical background, presence of acid reflux, and body mass index, the surgeon selects the most appropriate technique:
                </p>

                <h3 class="text-xl font-bold text-gray-900 mt-6 mb-3">1. Laparoscopic Sleeve Gastrectomy (LSG)</h3>
                <p>
                    The sleeve gastrectomy is the most popular metabolic surgery. Guided by a calibrated bougie tube, linear staplers permanently remove roughly 75% to 80% of the stomach, including the fundus that produces hunger hormones. The remaining stomach forms a slender tube holding 90 to 120 milliliters, while natural valves remain intact.
                </p>

                <h3 class="text-xl font-bold text-gray-900 mt-6 mb-3">2. Roux-en-Y Gastric Bypass (RYGB)</h3>
                <p>
                    The Roux-en-Y gastric bypass creates both restriction and calibrated nutrient redirection. The surgeon creates a small pouch holding 25 to 30 milliliters from the upper stomach. The small intestine is divided, and the lower limb connects directly to the new pouch so digestive juices meet food further downstream.
                </p>

                <h3 class="text-xl font-bold text-gray-900 mt-6 mb-3">3. One Anastomosis Gastric Bypass (OAGB)</h3>
                <p>
                    In One Anastomosis Gastric Bypass, the surgeon creates a narrow stomach pouch and connects it to a loop of small intestine in a single joint. This provides a shorter operative duration while delivering exceptional glycemic control for patients with type 2 diabetes.
                </p>

