                <h2 id="hormonal-and-metabolic-reset" class="text-2xl md:text-3xl font-bold text-gray-900 mt-10 mb-4 pt-4 border-t border-gray-100">
                    The Biological Shift: How Hormones and Digestion Change
                </h2>

                <p>
                    What happens physiologically following the operation explains why bariatric surgery produces long-term results that diet plans alone cannot achieve. For a closer look at these internal changes, explore our detailed article on the <a href="/blog/how-does-our-digestive-system-work-after-weight-loss-surgery" class="text-scod hover:text-blue-700 font-semibold underline decoration-scod/40">digestive system after surgery</a>.
                </p>

                <p>
                    In sleeve gastrectomy, removing the gastric fundus eliminates the primary source of ghrelin, the hormone responsible for appetite stimulation. Patients wake from surgery experiencing a noticeable drop in mental cravings for food.
                </p>

                <p>
                    In gastric bypass operations, nutrients arrive in the small intestine much sooner. This rapid arrival triggers intestinal cells to release satiety hormones, including glucagon-like peptide-1 (GLP-1) and peptide YY (PYY), signaling fullness to the brain and stimulating the pancreas to produce healthy insulin.
                </p>

                <p>
                    This hormonal surge explains why metabolic surgery leads to <a href="/blog/can-bariatric-surgery-reverse-diabetes" class="text-scod hover:text-blue-700 font-semibold underline decoration-scod/40">reversing type 2 diabetes</a> in up to 80% of eligible patients within days of surgery, well before significant weight is lost.
                </p>

