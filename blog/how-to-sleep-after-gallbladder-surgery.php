                <h2 class="text-2xl font-bold text-gray-900 mt-8 mb-4">Practical Tips for a Pain-Free Night's Sleep</h2>
                <p class="mb-6 font-semibold text-gray-800 bg-blue-50 border-l-4 border-scod p-4 rounded-r-xl">
                    Utilizing strategic pillow arrangements, executing the log-rolling technique, timing pain medications, and optimizing your bedroom setup promote comfortable sleep.
                </p>
                <p class="mb-6">
                    Implementing structured bedtime habits helps reduce physical discomfort and improves sleep duration throughout recovery:
                </p>

                <h3 class="text-xl font-bold text-gray-900 mt-6 mb-3">1. Strategic Pillow Placement</h3>
                <p class="mb-4">
                    Pillows play a crucial role when configuring <strong>how to sleep after gallbladder surgery</strong>:
                </p>
                <ul class="list-disc list-inside mb-6 space-y-2 text-gray-600">
                    <li><strong>Wedge Support Pillow:</strong> Maintains your head and chest at an elevated 30 to 45-degree angle.</li>
                    <li><strong>Under-Knee Support:</strong> Placed under knees to relieve pressure on the lower back and core muscles.</li>
                    <li><strong>Abdominal Cushion:</strong> A small pillow hugged gently against the abdomen to brace during coughing or turning.</li>
                </ul>

                <h3 class="text-xl font-bold text-gray-900 mt-6 mb-3">2. Master the Log-Rolling Technique</h3>
                <p class="mb-4">
                    Sitting straight up uses your abdominal muscles directly, which can cause sharp incision pain. Instead, practice the log-roll technique:
                </p>
                <ol class="list-decimal list-inside mb-6 space-y-2 text-gray-600">
                    <li>Sit down gently on the edge of your mattress.</li>
                    <li>Lower your torso onto your left side while swinging your legs up together onto the bed.</li>
                    <li>Roll smoothly onto your back using arm strength rather than twisting your core.</li>
                    <li>Reverse these exact steps when exiting bed to avoid pulling on healing incisions.</li>
                </ol>

                <h3 class="text-xl font-bold text-gray-900 mt-6 mb-3">3. Time Medications and Evening Movement</h3>
                <p class="mb-4">
                    Take your prescribed post-operative pain relief 30 to 45 minutes before going to sleep so peak pain relief coincides with bedtime. Engaging in a gentle 5 to 10-minute walk around your room an hour before bed stimulates circulation and helps your body absorb trapped laparoscopic gas, reducing night-time shoulder aches.
                </p>

                <h3 class="text-xl font-bold text-gray-900 mt-6 mb-3">4. Optimize Your Sleep Environment</h3>
                <p class="mb-4">
                    Keep your bedroom cool, quiet, and dark. Wear loose, breathable cotton clothing that does not feature tight elastic bands pressing across your upper stomach. Placing water and your phone within easy reach avoids unnecessary bending or stretching during the night.
                </p>

                <h2 class="text-2xl font-bold text-gray-900 mt-8 mb-4">When to Contact Your Surgeon</h2>
                <p class="mb-6 font-semibold text-gray-800 bg-blue-50 border-l-4 border-scod p-4 rounded-r-xl">
                    Severe night-time pain, fever, incision redness, unusual discharge, or shortness of breath require immediate medical evaluation.
                </p>
                <p class="mb-6">
                    While mild soreness is expected during early healing, contact your surgical team promptly if you experience red flag symptoms:
                </p>
                <ul class="list-disc list-inside mb-6 space-y-2 text-gray-600">
                    <li>Severe, unrelenting abdominal pain not relieved by prescribed pain medication.</li>
                    <li>Fever exceeding 100.4°F (38°C) or shaking chills.</li>
                    <li>Spreading redness, warmth, swelling, or foul-smelling drainage at incision sites.</li>
                    <li>Persistent nausea, vomiting, or inability to tolerate fluids.</li>
                    <li>Sudden chest pain or difficulty breathing.</li>
                </ul>
