                <!-- Section: Step-by-Step Food Journey -->
                <h2 class="text-2xl md:text-3xl font-bold text-gray-900 mt-10 mb-4 pt-4 border-t border-gray-100">
                    The Step-by-Step Journey of Food After Surgery
                </h2>

                <p>
                    Every phase of digestion adapts to your new gastrointestinal anatomy. Here is what happens when you eat a meal:
                </p>

                <h3 class="text-xl font-bold text-gray-900 mt-6 mb-2">1. Thorough Chewing in the Mouth</h3>
                <p>
                    Because your stomach no longer has a spacious churning cavity, your mouth must do the mechanical grinding work. Chewing every bite 25 to 30 times ensures food enters the pouch as a smooth liquid puree. Swallowing large chunks can block the narrow gastric outlet and cause nausea or esophageal spasms.
                </p>

                <h3 class="text-xl font-bold text-gray-900 mt-6 mb-2">2. Immediate Satiety Signals</h3>
                <p>
                    In an untreated stomach, fullness cues take up to 20 minutes to register in the brain. After surgery, stretch receptors inside the smaller pouch activate after just two or three small spoonfuls. These receptors send immediate signals through the vagus nerve, creating genuine physiological fullness.
                </p>

                <h3 class="text-xl font-bold text-gray-900 mt-6 mb-2">3. Acid Production and Protein Digestion</h3>
                <p>
                    Because parietal cell tissue is significantly reduced, the stomach produces less hydrochloric acid. While the acid is sufficient to maintain stomach hygiene, tender cooking methods like poaching, slow cooking, and steaming make protein breakdown easier on the digestive adaptation system.
                </p>

                <h3 class="text-xl font-bold text-gray-900 mt-6 mb-2">4. Rapid Intestinal Hormone Stimulation</h3>
                <p>
                    Food enters the small intestine much faster than before. When undigested proteins and carbohydrates reach the lower intestine earlier, specialized intestinal endocrine cells trigger powerful satiety signals that help control appetite and blood glucose.
                </p>

                <h3 class="text-xl font-bold text-gray-900 mt-6 mb-2">5. Shifts in Gut Microbiome Composition</h3>
                <p>
                    Following surgery, changes in gut acidity and bile flow encourage the growth of beneficial gut bacteria such as <em>Bacteroidetes</em>. This healthy bariatric gut microbiome improves metabolic rate, enhances gut barrier integrity, and lowers chronic inflammation.
                </p>

                <!-- Section: Gut Hormones & Endocrine Shifts -->
                <h2 class="text-2xl md:text-3xl font-bold text-gray-900 mt-10 mb-4 pt-4 border-t border-gray-100">
                    The Hormonal Reset: Appetite and Metabolic Regulation
                </h2>

                <p>
                    The key to sustained weight loss is not willpower alone; it is profound gut hormone regulation. Your digestive tract produces key hormones that regulate appetite, energy balance, and insulin sensitivity.
                </p>

                <div class="grid grid-cols-1 md:grid-cols-2 gap-6 my-8">
                    <div class="bg-blue-50 border border-blue-200 p-6 rounded-2xl">
                        <h3 class="text-lg font-bold text-scod mb-2">Drop in Hunger Hormone (Ghrelin)</h3>
                        <p class="text-sm text-gray-700 leading-relaxed">
                            Ghrelin stimulates appetite and causes hunger pangs. It is predominantly manufactured in the gastric fundus. When this area is excised or bypassed, blood ghrelin levels drop substantially, reducing food cravings and mental preoccupation with eating.
                        </p>
                    </div>

                    <div class="bg-emerald-50 border border-emerald-200 p-6 rounded-2xl">
                        <h3 class="text-lg font-bold text-emerald-800 mb-2">Surge in Satiety Hormones (GLP-1 & PYY)</h3>
                        <p class="text-sm text-gray-700 leading-relaxed">
                            Glucagon-like peptide-1 (GLP-1) and peptide YY (PYY) are released by cells in the lower intestine. The fast delivery of food stimulates substantial spikes in GLP-1 and PYY, signaling fullness to the brain and enhancing pancreatic insulin production.
                        </p>
                    </div>
                </div>

