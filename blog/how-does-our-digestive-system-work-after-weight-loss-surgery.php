                <h2 class="text-2xl md:text-3xl font-bold text-gray-900 mt-10 mb-4 pt-4 border-t border-gray-100">
                    Why Expert Surgical Care Ensures Healthy Digestion
                </h2>

                <p>
                    Long-term digestive comfort depends heavily on surgical precision. Crafting the proper sleeve diameter, creating a smooth gastrojejunal connection, and preserving delicate tissue blood flow require specialized experience.
