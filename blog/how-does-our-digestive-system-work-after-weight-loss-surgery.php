                <p class="text-lg text-gray-800 leading-relaxed font-normal">
                    When considering metabolic surgery, most people focus on weight numbers, smaller clothing sizes, and reversing chronic health issues. However, an essential question frequently arises: <em>How does our digestive system work after weight loss surgery?</em>
                </p>

                <p>
                    Your digestive system is far more than a simple food pouch. It is an intricate, thirty-foot biochemical pathway coordinating muscle movements, acid secretion, digestive enzymes, and neurological signals. After metabolic surgery, the way your gastrointestinal tract handles meals changes fundamentally.
                </p>

                <p>
                    According to <a href="https://scodclinic.com/about" class="text-scod hover:text-blue-700 font-semibold underline decoration-scod/40">Dr. Arush Sabharwal</a>, Chief Bariatric Surgeon at SCOD Clinic, understanding your altered digestive anatomy helps you adopt healthy eating habits, avoid common discomforts, and maintain optimal lifelong wellness.
                </p>

                <!-- Section: How Normal Digestion Operates -->
                <h2 class="text-2xl md:text-3xl font-bold text-gray-900 mt-10 mb-4 pt-4 border-t border-gray-100">
                    Understanding Normal Digestion: The Baseline Mechanism
                </h2>

                <p>
                    To understand post-surgical changes, let us first look at how the healthy <a href="https://en.wikipedia.org/wiki/Human_digestive_system" target="_blank" rel="noopener noreferrer" class="text-scod hover:text-blue-700 font-semibold underline decoration-scod/40">human digestive system</a> processes food before any medical procedure:
                </p>

                <ul class="list-disc pl-6 space-y-2 text-gray-700">
                    <li><strong>Mouth:</strong> Teeth chew food while salivary enzymes start carbohydrate breakdown.</li>
                    <li><strong>Esophagus:</strong> Peristaltic waves push the food bolus downward through the lower esophageal sphincter.</li>
                    <li><strong>Stomach:</strong> A typical stomach holds 1.5 to 2 liters of food and liquid. It secretes hydrochloric acid and pepsin to liquefy food into acidic chyme.</li>
                    <li><strong>Pyloric Sphincter:</strong> This muscular valve slowly releases spoonfuls of chyme into the small intestine.</li>
                    <li><strong>Duodenum:</strong> Pancreatic juices and liver bile neutralize stomach acid and digest dietary fats, carbohydrates, and proteins.</li>
                    <li><strong>Jejunum and Ileum:</strong> The middle and lower small intestine absorb essential nutrients into the bloodstream.</li>
                    <li><strong>Colon:</strong> The large intestine absorbs water and electrolytes, while trillions of bacteria ferment dietary fiber before waste elimination.</li>
                </ul>

                <p>
                    Under ordinary conditions, this complete cycle takes between 24 and 72 hours. Metabolic procedures alter specific stages of this journey to bring about lasting weight control.
                </p>

                <!-- Section: Physical Anatomical Changes -->
                <h2 class="text-2xl md:text-3xl font-bold text-gray-900 mt-10 mb-4 pt-4 border-t border-gray-100">
                    The Physical Transformation: Sleeve Gastrectomy vs. Gastric Bypass
                </h2>

                <p>
                    The exact bariatric digestive process depends on whether you have a restrictive procedure or a combined restrictive and malabsorptive procedure.
                </p>

                <h3 class="text-xl font-bold text-gray-900 mt-6 mb-3">1. Sleeve Gastrectomy Digestive Changes</h3>
                <p>
                    During sleeve gastrectomy, surgeons laparoscopically remove roughly 80% of the stomach along its outer curvature. The remaining portion forms a slender vertical tube holding approximately 90 to 120 milliliters (around 3 to 4 ounces) in the initial post-surgical period.
                </p>
                <p>
                    Importantly, sleeve gastrectomy digestive changes preserve both the entry and exit valves of the stomach. Food still passes from the esophagus into the sleeve, passes through the pyloric valve, and traverses the entire duodenum and jejunum. Because the pylorus remains intact, gastric emptying speed stays relatively regulated, although high pressure inside the narrow tube promotes quicker delivery to the small intestine.
                </p>

                <h3 class="text-xl font-bold text-gray-900 mt-6 mb-3">2. Roux-en-Y Gastric Bypass Digestion</h3>
                <p>
                    Gastric bypass reorganizes both the stomach and the small intestine. The surgeon divides the upper stomach into a small gastric pouch digestion chamber about the size of an egg (holding 25 to 30 milliliters).
                </p>
                <p>
                    The lower stomach and duodenum are bypassed. A section of the jejunum is connected directly to the small pouch through small intestine rerouting. Digested food leaves the pouch without passing through the pyloric sphincter, flowing straight into the jejunum. Digestive juices travel through a separate intestinal limb and mix with food further downstream in the common channel.
                </p>

