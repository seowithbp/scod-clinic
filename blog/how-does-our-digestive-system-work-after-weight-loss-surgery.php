                <!-- Section: Nutrient Absorption & Micronutrient Care -->
                <h2 class="text-2xl md:text-3xl font-bold text-gray-900 mt-10 mb-4 pt-4 border-t border-gray-100">
                    Nutrient Absorption After Weight Loss Surgery
                </h2>

                <p>
                    Because gastric volume is reduced and digestive pathways are redirected, nutrient absorption after weight loss surgery requires attentive care:
                </p>

                <ul class="list-disc pl-6 space-y-3 text-gray-700">
                    <li>
                        <strong>Vitamin B12:</strong> B12 needs intrinsic factor, produced by stomach parietal cells, to be absorbed. With a smaller stomach, routine B12 sublingual tablets or periodic injections prevent anemia and nerve fatigue.
                    </li>
                    <li>
                        <strong>Iron:</strong> Iron is mainly absorbed in the duodenum. In gastric bypass, the bypassed duodenum reduces natural iron uptake. Taking iron with vitamin C enhances absorption.
                    </li>
                    <li>
                        <strong>Calcium & Vitamin D:</strong> Reduced gastric acidity makes calcium citrate the preferred supplement form, as it does not require strong stomach acid for uptake, preserving healthy bones.
                    </li>
                    <li>
                        <strong>Daily Dietary Protein:</strong> Meeting a goal of 60 to 80 grams of daily protein protects lean muscle tissue. For practical tips on protecting your hair during early weight loss, review our advice on <a href="/blog/how-to-stop-hair-loss-after-bariatric-surgery" class="text-scod hover:text-blue-700 font-semibold underline decoration-scod/40">post-bariatric hair care</a>.
                    </li>
                </ul>

                <!-- Section: Digestive Sensations & Adjustments -->
                <h2 class="text-2xl md:text-3xl font-bold text-gray-900 mt-10 mb-4 pt-4 border-t border-gray-100">
                    Common Digestive Sensations and Adjustments
                </h2>

                <p>
                    As your body adjusts during the first several months, you may experience different bodily signals:
                </p>

                <h3 class="text-xl font-bold text-gray-900 mt-6 mb-2">1. Recognizing Satiety Cues</h3>
                <p>
                    Rather than a feeling of abdominal stretching, your new fullness cues may present as a quiet hiccup, a gentle sigh, or mild pressure beneath the breastbone. Stopping at this warning prevents nausea, regurgitation, or esophageal fullness.
                </p>

                <h3 class="text-xl font-bold text-gray-900 mt-6 mb-2">2. Managing Dumping Syndrome Symptoms</h3>
                <p>
                    Consuming high-sugar foods or sugary drinks can pull fluid rapidly into the jejunum. This triggers dumping syndrome symptoms including rapid pulse, sweating, lightheadedness, and temporary diarrhea. Choosing balanced, whole foods prevents this response completely.
                </p>

                <h3 class="text-xl font-bold text-gray-900 mt-6 mb-2">3. Changes in Bowel Frequency</h3>
                <p>
                    Smaller food portions naturally lead to less frequent bowel movements, often once every two or three days. Drinking plenty of water between meals and following a clear <a href="/blog/what-to-eat-after-laparoscopic-surgery" class="text-scod hover:text-blue-700 font-semibold underline decoration-scod/40">post-laparoscopic diet guide</a> keeps your digestion regular and comfortable.
                </p>

