                    <h2 class="text-2xl md:text-3xl font-extrabold text-gray-900 tracking-tight">Understanding Bariatric Surgery Safety After a Heart Attack</h2>
                    <p>
                        Experiencing an acute coronary event such as a <a href="https://en.wikipedia.org/wiki/Myocardial_infarction" target="_blank" rel="noopener noreferrer" class="text-scod hover:underline font-medium">myocardial infarction</a> is a profound wake-up call. For individuals living with obesity, a heart attack highlights the urgent need to address systemic vascular risks, high cholesterol, and chronic metabolic stress. While a history of cardiovascular disease was once seen as an absolute barrier to elective surgery, modern metabolic medicine has transformed this view.
                    </p>
                    <p>
                        Today, clinical evidence confirms that heart attack survivors are not automatically disqualified from weight loss surgery. Carrying significant excess weight after a cardiac event places ongoing mechanical strain on the left ventricle and accelerates arterial plaque buildup. When performed with advanced minimally invasive techniques and attentive cardiac monitoring, bariatric procedures provide an effective secondary intervention to halt disease progression and protect against future coronary events.
                    </p>
                    <p>
                        The goal after a heart attack is stabilizing heart muscle while addressing the underlying metabolic drivers of vascular disease. Understanding <a href="/blog/why-obesity-is-health-problem" class="text-scod font-semibold hover:underline">severe obesity health risks</a> enables patients and clinicians to determine the safest surgical timing.
                    </p>
                </section>

                <!-- Section 2 -->
                <section id="recommended-waiting-timeline" class="space-y-4">
                    <h2 class="text-2xl md:text-3xl font-extrabold text-gray-900 tracking-tight">How Long Must You Wait After a Cardiac Event?</h2>
                    <p>
                        Timing is critical when planning surgery after a heart attack. Operating prematurely during the acute healing phase carries elevated cardiac risk, whereas waiting allows damaged myocardial tissue to consolidate and heart function to stabilize.
                    </p>
                    <p>
                        Cardiovascular and bariatric guidelines recommend a waiting window of 6 to 12 months following a heart attack before elective metabolic surgery:
                    </p>
                    <ul class="list-disc list-inside space-y-2 pl-2">
                        <li>Ventricular Remodeling: Injured myocardium undergoes cellular repair over several months. Delaying surgery reduces the risk of arrhythmias and acute decompensation.</li>
                        <li>Stent Endothelialization: If you received a drug-eluting stent (DES), the metallic scaffold requires 6 to 12 months to become fully endothelialized, preventing stent thrombosis.</li>
                        <li>Antiplatelet Therapy Stability: Patients must complete their prescribed dual antiplatelet therapy before temporarily pausing any medication for surgery.</li>
                        <li>Hemodynamic Stability: Resting heart rate, blood pressure, and left ventricular function reach a stable baseline under optimized cardiac medications.</li>
                    </ul>
                    <p>
                        In stable cases where revascularization was complete, heart muscle damage was minimal, and cardiac stress tests confirm normal perfusion, surgical evaluation can begin as early as six months post-event.
                    </p>
                </section>

                <!-- Section 3 -->
                <section id="preoperative-cardiac-clearance" class="space-y-4">
