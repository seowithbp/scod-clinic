                            </h4>
                            <p class="text-sm text-gray-600">
                                Severe obstructive sleep apnea places profound nocturnal strain on cardiac chambers. Preoperative diagnosis and CPAP therapy optimization ensure airway safety and cardiac stability during recovery.
