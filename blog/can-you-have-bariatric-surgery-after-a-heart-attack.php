                <section id="proven-cardiovascular-benefits" class="space-y-4">
                    <h2 class="text-2xl md:text-3xl font-extrabold text-gray-900 tracking-tight">Proven Long-Term Cardiovascular Benefits of Metabolic Surgery</h2>
                    <p>
                        The cardiovascular improvements following bariatric surgery are profound. Beyond weight loss, metabolic surgery acts as powerful secondary prevention in patients with established coronary artery disease:
                    </p>
                    <div class="space-y-3 pl-2">
                        <p>
                            Reduction in Secondary Events: Heart disease patients undergoing bariatric surgery experience up to a 40% to 50% reduction in recurrent cardiovascular events, strokes, and cardiac mortality compared to non-surgical care.
                        </p>
                        <p>
                            Decreased Cardiac Workload: Losing 25% to 35% of total body weight decreases systemic vascular resistance and left ventricular afterload, reducing resting heart strain and enhancing myocardial pumping efficiency.
                        </p>
                        <p>
                            Reversal of Plaque Drivers: Metabolic surgery reduces systemic inflammation (hs-CRP), lowers triglycerides and small dense LDL, while elevating protective HDL cholesterol to stabilize arterial walls.
                        </p>
                        <p>
                            Diabetes and Hypertension Remission: Over 70% of patients achieve remission of type 2 diabetes, preventing continuing vascular and coronary endothelial injury.
                        </p>
                    </div>
                    <p>
                        As patients achieve <a href="/blog/is-sagging-skin-after-bariatric-surgery-normal" class="text-scod font-semibold hover:underline">rapid post-surgical weight loss</a>, they experience increased physical endurance and lower cardiac medication requirements.
                    </p>
                </section>

                <!-- Section 7 -->
                <section id="postoperative-recovery-and-rehab" class="space-y-4">
                    <h2 class="text-2xl md:text-3xl font-extrabold text-gray-900 tracking-tight">Postoperative Recovery, Fluid Balance, and Cardiac Rehabilitation</h2>
                    <p>
                        The postoperative period for a cardiac patient requires heightened attention to fluid balance, mobility, and progressive physical rehabilitation. Because the heart muscle has reduced physiological reserves, maintaining smooth hemodynamics is essential:
                    </p>
                    <ul class="list-disc list-inside space-y-2 pl-2">
                        <li>Careful Fluid Management: Intraoperative and post-surgical intravenous fluids are administered with precision to prevent both hypovolemic hypotension and fluid overload, which could precipitate pulmonary edema in a vulnerable ventricle.</li>
                        <li>Early Ambulation and DVT Prophylaxis: Gentle walking within hours of surgery helps stimulate circulation, lowers the risk of venous thromboembolism, and aids respiratory clearing.</li>
                        <li>Coordination with Cardiac Rehab: Once cleared by your surgical team, enrolling in formal outpatient cardiac rehabilitation offers a safe, monitored environment to rebuild stamina using <a href="/blog/when-can-i-start-exercising-after-bariatric-surgery" class="text-scod font-semibold hover:underline">safe cardiovascular exercise routines</a> designed for post-surgical recovery.</li>
                        <li>Micronutrient and Electrolyte Monitoring: Regular post-bariatric blood panels ensure that essential serum electrolytes, such as potassium and magnesium, remain in optimal ranges to protect against heart rhythm abnormalities.</li>
                    </ul>
                </section>

