                                Transthoracic Echocardiogram (TTE)
                            </h4>
                            <p class="text-sm text-gray-600">
                                Measures left ventricular ejection fraction (LVEF), assesses wall motion abnormalities resulting from the heart attack, and detects potential heart valve disorders or elevated pulmonary artery pressures.
