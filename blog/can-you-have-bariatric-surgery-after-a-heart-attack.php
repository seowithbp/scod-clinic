                    <p>
                        Securing formal medical clearance for bariatric surgery after a heart attack requires a thorough, multifaceted diagnostic workup. Your surgical team collaborates directly with your primary cardiologist to ensure that the cardiovascular system can tolerate general anesthesia, abdominal insufflation, and intraoperative fluid dynamics.
                    </p>
                    <p>
                        The diagnostic evaluation generally encompasses the following standard medical assessments:
                    </p>
