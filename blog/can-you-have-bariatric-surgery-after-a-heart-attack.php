                <!-- Section 4 -->
                <section id="choosing-the-safest-bariatric-procedure" class="space-y-4">
                    <h2 class="text-2xl md:text-3xl font-extrabold text-gray-900 tracking-tight">Which Bariatric Procedure Offers the Highest Safety Profile?</h2>
                    <p>
                        When treating patients with pre-existing coronary artery disease, selecting the optimal surgical approach involves balancing procedural duration, metabolic potency, and medication pharmacokinetics. Both laparoscopic sleeve gastrectomy and Roux-en-Y gastric bypass deliver outstanding results, but each carries specific clinical implications for cardiac patients:
                    </p>
                    <div class="space-y-4">
                        <div class="border border-gray-200 rounded-xl p-6 bg-white shadow-sm">
                            <h3 class="text-xl font-bold text-gray-900 mb-2">Laparoscopic Sleeve Gastrectomy (LSG)</h3>
                            <p class="mb-3">
                                Sleeve gastrectomy is frequently considered the first-line choice for post-myocardial infarction candidates. The operation typically requires shorter anesthesia time, generally between 45 to 60 minutes, which minimizes prolonged intra-abdominal pressure from pneumoperitoneum.
                            </p>
                            <p class="text-sm text-gray-600">
                                Furthermore, because the gastrointestinal tract is not rerouted, sleeve gastrectomy maintains normal physiological drug absorption. This is an immense clinical benefit for patients reliant on precision cardiovascular medications such as beta-blockers, ACE inhibitors, novel oral anticoagulants (DOACs), and statins.
                            </p>
                        </div>

                        <div class="border border-gray-200 rounded-xl p-6 bg-white shadow-sm">
                            <h3 class="text-xl font-bold text-gray-900 mb-2">Roux-en-Y Gastric Bypass (RYGB)</h3>
                            <p class="mb-3">
                                Gastric bypass remains an exceptionally effective procedure, particularly for individuals experiencing severe uncontrolled type 2 diabetes or intractable gastroesophageal reflux disease. However, the procedure involves intestinal rerouting, longer operative duration, and altered nutrient absorption.
                            </p>
                            <p class="text-sm text-gray-600">
                                In heart attack survivors, bypass patients require closer monitoring for dumping syndrome, rapid fluid shifts, and potential variations in medication bioavailability. In seasoned surgical hands, both procedures are performed with low complication rates.
                            </p>
                        </div>
                    </div>
                </section>

                <!-- Section 5 -->
                <section id="blood-thinners-and-stent-management" class="space-y-4">
                    <h2 class="text-2xl md:text-3xl font-extrabold text-gray-900 tracking-tight">Navigating Blood Thinners, Stents, and Perioperative Medications</h2>
                    <p>
                        Managing antiplatelet and anticoagulant medications is essential for post-infarction surgical safety. Discontinuing blood thinners too early exposes coronary stents to thrombosis, whereas continuing full platelet inhibition during surgery increases bleeding risk.
                    </p>
                    <p>
                        To ensure safety, the surgical team follows a coordinated cardiology protocol:
                    </p>
                    <ul class="list-disc list-inside space-y-2 pl-2">
                        <li>Aspirin Continuation: Low-dose aspirin (75–100 mg daily) is frequently maintained through surgery without significant bleeding risk.</li>
                        <li>P2Y12 Inhibitors: Clopidogrel, ticagrelor, or prasugrel are paused 5 to 7 days before surgery only after the mandatory stenting period is complete and cleared by your cardiologist.</li>
                        <li>Bridging Anticoagulation: For patients with atrial fibrillation or mechanical valves, low-molecular-weight heparin bridging is utilized when necessary.</li>
                        <li>Prompt Resumption: Blood thinners are safely restarted within 24 to 48 hours post-operation once surgical hemostasis is confirmed.</li>
                    </ul>
                    <p>
                        Daily medications such as beta-blockers are taken on the morning of surgery with a sip of water to avoid rebound tachycardia and sudden blood pressure spikes.
                    </p>
                </section>

