                <h2 class="text-2xl font-bold text-gray-900 mt-10 mb-4">Why Does Hernia Come Back After Surgery? Key Causes</h2>

                <p class="mb-6 leading-relaxed">
                    A hernia does not return by chance. When recurrence occurs, it is typically driven by a combination of physical strain, systemic health conditions, and surgical factors:
                </p>

                <div class="space-y-6 my-6">
                    <div class="border-l-4 border-scod pl-4 bg-gray-50/60 p-4 rounded-r-xl">
                        <h3 class="font-bold text-gray-900 text-lg flex items-center gap-2">
                            <i data-feather="alert-circle" class="w-5 h-5 text-scod"></i>
                            1. Premature Heavy Lifting and Physical Strain
                        </h3>
                        <p class="text-gray-600 mt-2 text-sm leading-relaxed">
                            Following surgery, your body requires 6 to 8 weeks to weave new collagen fibers securely through the mesh pores. Lifting heavy weights, moving heavy items, or returning to strenuous workouts too soon creates sudden intra-abdominal pressure that can dislodge the mesh or tear healing tissue before it achieves full tensile strength.
                        </p>
                    </div>

                    <div class="border-l-4 border-scod pl-4 bg-gray-50/60 p-4 rounded-r-xl">
                        <h3 class="font-bold text-gray-900 text-lg flex items-center gap-2">
                            <i data-feather="wind" class="w-5 h-5 text-scod"></i>
                            2. Repetitive High Intra-Abdominal Pressure
                        </h3>
                        <p class="text-gray-600 mt-2 text-sm leading-relaxed">
                            Frequent, sharp spikes in abdominal pressure subject the repair line to repeated mechanical stress:
                        </p>
                        <ul class="list-disc list-inside text-gray-600 text-sm mt-2 space-y-1">
                            <li><strong>Chronic coughing:</strong> Common in smokers, asthmatics, and patients with allergies or bronchitis.</li>
                            <li><strong>Severe constipation:</strong> Straining during bowel movements exerts downward force on the lower abdominal wall.</li>
                            <li><strong>Urinary straining:</strong> An enlarged prostate (BPH) causes men to strain during urination.</li>
                        </ul>
                    </div>

                    <div class="border-l-4 border-scod pl-4 bg-gray-50/60 p-4 rounded-r-xl">
                        <h3 class="font-bold text-gray-900 text-lg flex items-center gap-2">
                            <i data-feather="shield-off" class="w-5 h-5 text-scod"></i>
                            3. Surgical Site Infection
                        </h3>
                        <p class="text-gray-600 mt-2 text-sm leading-relaxed">
                            If an infection develops, inflammatory enzymes degrade healing collagen, disrupting tissue ingrowth into the mesh and leaving the muscle layer weak.
                        </p>
                    </div>

                    <div class="border-l-4 border-scod pl-4 bg-gray-50/60 p-4 rounded-r-xl">
                        <h3 class="font-bold text-gray-900 text-lg flex items-center gap-2">
                            <i data-feather="user-x" class="w-5 h-5 text-scod"></i>
                            4. Patient Health and Lifestyle Factors
                        </h3>
                        <p class="text-gray-600 mt-2 text-sm leading-relaxed">
                            Systemic conditions greatly influence healing:
                        </p>
                        <ul class="list-disc list-inside text-gray-600 text-sm mt-2 space-y-1">
                            <li><strong>Obesity:</strong> Excess visceral fat exerts continuous outward pressure on the abdominal muscles.</li>
                            <li><strong>Smoking:</strong> Nicotine restricts blood flow, impairing collagen synthesis and multiplying recurrence risk.</li>
                            <li><strong>Diabetes:</strong> Elevated glucose impairs immune defenses and delays healing.</li>
                            <li><strong>Poor Nutrition:</strong> Insufficient protein limits the essential building blocks for tissue repair.</li>
                        </ul>
                    </div>

                    <div class="border-l-4 border-scod pl-4 bg-gray-50/60 p-4 rounded-r-xl">
                        <h3 class="font-bold text-gray-900 text-lg flex items-center gap-2">
                            <i data-feather="tool" class="w-5 h-5 text-scod"></i>
                            5. Mesh Sizing and Surgical Technique
                        </h3>
                        <p class="text-gray-600 mt-2 text-sm leading-relaxed">
                            Adequate mesh overlap beyond the defect edges (typically 3 to 5 cm) is critical. If overlap is insufficient or fixation is loose, tissue can slip past the mesh edge, highlighting the value of choosing a fellowship-trained laparoscopic surgeon.
                        </p>
                    </div>
