                <h2 class="text-2xl font-bold text-gray-900 mt-10 mb-4">What Is a Recurrent Hernia?</h2>

                <p class="mb-6 leading-relaxed">
                    An abdominal or groin <a href="https://en.wikipedia.org/wiki/Hernia" target="_blank" rel="noopener noreferrer" class="text-scod hover:text-blue-700 font-semibold underline">hernia</a> occurs when internal tissue—such as loops of the intestine or protective fatty layers—protrudes through a weak spot or opening in the surrounding muscle wall.
                </p>

                <p class="mb-6 leading-relaxed">
