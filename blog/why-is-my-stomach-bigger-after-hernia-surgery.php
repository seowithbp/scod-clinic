                <h2 class="text-2xl font-bold text-gray-900 mt-10 mb-4">7 Reasons Why Your Stomach Looks or Feels Bigger After Hernia Surgery</h2>

                <p class="mb-6 leading-relaxed">
                    Hernia surgery involves delicate manipulation of muscular layers, fascia, and connective tissues. Even with minimally invasive keyhole techniques, the body triggers a protective biological response. Below are the seven primary reasons for your enlarged abdomen:
                </p>

                <!-- Cause 1 -->
                <div class="bg-gray-50 p-6 rounded-2xl border border-gray-200 mb-6">
                    <h3 class="text-xl font-bold text-gray-900 mb-2 flex items-center gap-2">
                        <span class="w-8 h-8 rounded-full bg-scod text-white flex items-center justify-center text-sm font-bold">1</span>
                        Trapped Carbon Dioxide Gas (Laparoscopic Insufflation)
                    </h3>
                    <p class="text-gray-700 leading-relaxed mb-2">
                        During keyhole or robotic surgery, the surgeon gently inflates your abdominal cavity with medical-grade carbon dioxide (CO2). This expands the belly like a dome, creating clear visibility and operating space.
                    </p>
                    <p class="text-gray-600 text-sm leading-relaxed">
                        Although most gas is removed before closing the incisions, small pockets remain trapped under your diaphragm and abdominal lining. This creates visible bloating and can cause referred ache in the right shoulder. Learn simple ways to relieve this in our guide on <a href="/blog/how-to-get-rid-of-co2-after-laparoscopic-surgery" class="text-scod hover:underline font-semibold">how to get rid of CO2 after laparoscopic surgery</a>.
                    </p>
                </div>

                <!-- Cause 2 -->
                <div class="bg-gray-50 p-6 rounded-2xl border border-gray-200 mb-6">
                    <h3 class="text-xl font-bold text-gray-900 mb-2 flex items-center gap-2">
                        <span class="w-8 h-8 rounded-full bg-scod text-white flex items-center justify-center text-sm font-bold">2</span>
                        Normal Post-Surgical Tissue Edema (Inflammation)
                    </h3>
                    <p class="text-gray-700 leading-relaxed mb-2">
                        Any incision or tissue repair triggers an acute healing response. The immune system rushes white blood cells, lymphatic fluids, and blood flow to the site to knit tissues back together.
                    </p>
                    <p class="text-gray-600 text-sm leading-relaxed">
                        This localized fluid accumulation—called <strong>edema</strong>—spreads through the soft tissues of the lower belly, creating a swollen, puffy appearance that is most noticeable during the first 1 to 2 weeks.
                    </p>
                </div>

                <!-- Cause 3 -->
                <div class="bg-gray-50 p-6 rounded-2xl border border-gray-200 mb-6">
                    <h3 class="text-xl font-bold text-gray-900 mb-2 flex items-center gap-2">
                        <span class="w-8 h-8 rounded-full bg-scod text-white flex items-center justify-center text-sm font-bold">3</span>
                        Formation of a Seroma (Fluid in the "Dead Space")
                    </h3>
                    <p class="text-gray-700 leading-relaxed mb-2">
                        Before surgery, your hernia pushed outward, stretching surrounding tissue into an empty pocket. Once the protruding tissue is reduced and reinforced with mesh, that empty pocket remains.
                    </p>
                    <p class="text-gray-600 text-sm leading-relaxed">
                        The body naturally fills this "dead space" with clear lymphatic fluid, forming a <strong>seroma</strong>. A seroma can feel like a firm or squishy lump right where your hernia used to be. Patients often mistake it for a recurring hernia, but it is harmless fluid that the body slowly reabsorbs over 4 to 12 weeks.
                    </p>
                </div>

