                        Bowel Sluggishness, Constipation, and Trapped Gas
                    </h3>
                    <p class="text-gray-700 leading-relaxed mb-2">
                        General anesthesia temporarily relaxes digestive muscular contractions. Additionally, narcotic pain relievers slow intestinal transit times, frequently leading to constipation.
                    </p>
                    <p class="text-gray-600 text-sm leading-relaxed">
                        When stool and digestive gas back up in your colon, your intestines dilate and push outward against the abdominal wall. This makes the stomach feel tight, swollen, and bloated. Check our recommendations on <a href="/blog/what-to-eat-after-laparoscopic-surgery" class="text-scod hover:underline font-semibold">what to eat after laparoscopic surgery</a> to maintain easy bowel movements without straining.
