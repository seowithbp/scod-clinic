                    <h3 class="text-xl font-bold text-gray-900 mb-2 flex items-center gap-2">
                        <span class="w-8 h-8 rounded-full bg-scod text-white flex items-center justify-center text-sm font-bold">5</span>
                        Temporary Loss of Abdominal Muscle Tone
                    </h3>
                    <p class="text-gray-700 leading-relaxed mb-2">
                        Your abdominal core acts like a natural corset holding internal organs in place. Following surgery, local discomfort and nerve reflexes cause these muscles to relax involuntarily to avoid tension on the repair.
                    </p>
                    <p class="text-gray-600 text-sm leading-relaxed">
                        Without active muscle tone, your abdominal contents shift forward when standing, creating a temporary "pouch" effect. Core support naturally returns as soreness clears and walking increases.
                    </p>
