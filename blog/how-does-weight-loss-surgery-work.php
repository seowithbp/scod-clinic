                <ol class="list-decimal list-inside space-y-4 my-6 pl-2">
                    <li class="pl-2">
                        <strong>Minimally Invasive Keyhole Technique:</strong> Bariatric surgeries are performed laparoscopically or robotically through 4 to 5 tiny puncture cuts (each 5 mm to 12 mm wide) rather than open abdominal incisions. High-definition cameras and precision articulated instruments allow the surgeon to operate with sub-millimeter precision.
                    </li>
