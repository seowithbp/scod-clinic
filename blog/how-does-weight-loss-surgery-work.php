                    1. Physical Restriction: Satiety with Smaller Quantities
                </h3>
                <p>
                    A standard adult stomach can expand to hold between 1.5 to 2 liters of food and liquid. During surgical procedures such as the Sleeve Gastrectomy or Roux-en-Y Gastric Bypass, the usable capacity of the stomach is reduced to roughly 90 to 150 milliliters (about the size of a small banana or an egg).
