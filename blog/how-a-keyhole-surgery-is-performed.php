                    <p class="text-gray-800 leading-relaxed">
                        A <strong>keyhole surgery</strong> (laparoscopy) is performed under general anesthesia through <strong>2 to 4 tiny incisions (5 to 10 mm)</strong> instead of a large opening. First, the surgeon gently inflates the abdomen with medical-grade carbon dioxide gas to create a clear working space. Next, a specialized high-definition camera (laparoscope) and slender instruments are inserted through narrow tubes called trocars. Guided by magnified, real-time video on a surgical monitor, the surgeon cuts, repairs, or removes tissue with microscopic precision. Finally, the gas is expelled and incisions are sealed with dissolvable stitches or surgical glue.
                    </p>
