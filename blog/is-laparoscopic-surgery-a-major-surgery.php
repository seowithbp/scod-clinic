                <div class="space-y-4 my-6">
                    <div class="border-l-4 border-scod pl-4 py-1">
                        <h4 class="font-bold text-gray-900 text-base">1. Administration of General Anesthesia</h4>
                        <p class="text-gray-600 text-sm mt-1 leading-relaxed">
                            Laparoscopy requires complete muscular relaxation. An anesthesiologist administers intravenous medications, places a breathing tube, and controls your ventilation. Managing respiration and hemodynamics while the body undergoes surgical stress is a hallmark of major interventions.
                        </p>
                    </div>

                    <div class="border-l-4 border-scod pl-4 py-1">
                        <h4 class="font-bold text-gray-900 text-base">2. Pneumoperitoneum and Cardiovascular Changes</h4>
                        <p class="text-gray-600 text-sm mt-1 leading-relaxed">
                            Surgeons gently inflate the abdomen with medical carbon dioxide (CO2) gas to create a working dome. This elevated intra-abdominal pressure alters venous return to the heart and elevates the diaphragm, requiring active hemodynamic monitoring.
                        </p>
                    </div>

                    <div class="border-l-4 border-scod pl-4 py-1">
                        <h4 class="font-bold text-gray-900 text-base">3. Internal Visceral Organ Dissection</h4>
                        <p class="text-gray-600 text-sm mt-1 leading-relaxed">
                            The internal surgical work—such as clipping arteries, dissecting ducts, removing an infected appendix, or anchoring prosthetic mesh—is identical to open surgery. The body must coordinate extensive cellular healing internally regardless of how the instruments entered.
                        </p>
                    </div>
                </div>

                <h2 class="text-2xl font-bold text-gray-900 mt-10 mb-4">The Laparoscopic Paradox: Why People Underestimate Keyhole Surgery</h2>
                <p class="text-gray-600 mb-6 leading-relaxed">
                    If keyhole surgery is indeed a major procedure, why do so many patients treat it like a minor checkup? Doctors call this the "laparoscopic paradox," and it arises from three simple reasons:
                </p>

                <ul class="list-disc list-inside text-gray-600 mb-6 space-y-2 text-sm leading-relaxed">
                    <li><strong>Small External Incisions:</strong> Puncture wounds measuring 5 to 10 millimeters leave tiny dressings, leading patients to assume little was done internally.</li>
                    <li><strong>Less Muscle Severing:</strong> Laparoscopic trocars separate muscle fibers instead of cutting across large muscle groups, significantly reducing post-surgical nerve pain.</li>
                    <li><strong>Short Hospitalization:</strong> Many laparoscopic procedures allow discharge within 24 hours, giving the false impression of an outpatient cosmetic treatment.</li>
                </ul>

