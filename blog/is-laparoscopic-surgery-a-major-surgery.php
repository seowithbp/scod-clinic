                <p class="text-gray-600 mb-6 leading-relaxed">
                    The clinical classification of modern <a href="https://en.wikipedia.org/wiki/Laparoscopy" target="_blank" rel="noopener noreferrer" class="text-scod hover:text-blue-700 underline font-medium">laparoscopy</a> is determined by three fundamental medical factors:
