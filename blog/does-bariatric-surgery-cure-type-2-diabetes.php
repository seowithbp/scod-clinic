                <h2 class="text-2xl font-bold text-gray-900 mt-8 mb-4">Types of Bariatric Surgery Used for Diabetes</h2>

                <p class="text-gray-600 mb-6">Several bariatric procedures are commonly performed for weight loss and diabetes improvement.</p>

                <h3 class="text-xl font-semibold text-gray-900 mb-3">Roux-En Y Gastric Bypass</h3>

                <p class="text-gray-600 mb-6">In Roux-en-Y gastric bypass surgery, the stomach is made smaller and connected directly to the small intestine. This reduces food intake and calorie absorption. This procedure is known for strong diabetes remission results because it also changes gut hormones that affect insulin function.</p>

                <h3 class="text-xl font-semibold text-gray-900 mb-3">Sleeve Gastrectomy</h3>

                <p class="text-gray-600 mb-6">In sleeve gastrectomy, a large part of the stomach is removed, leaving a smaller tube-shaped stomach. This surgery reduces hunger hormones and helps patients eat less while improving insulin sensitivity.</p>

                <h3 class="text-xl font-semibold text-gray-900 mb-3">Mini Gastric Bypass</h3>

                <p class="text-gray-600 mb-6">This is a simpler variation of gastric bypass surgery and is also effective for obesity and diabetes management.</p>

                <h3 class="text-xl font-semibold text-gray-900 mb-3">Adjustable Gastric Band</h3>

                <p class="text-gray-600 mb-6">A band is placed around the stomach to reduce food intake. However, this procedure is less common today because other surgeries generally provide better long-term results.</p>

