                <p class="text-gray-600 mb-6">Bariatric surgery refers to different surgical procedures that help people lose weight by changing the digestive system. These surgeries reduce food intake and may also affect hormones related to hunger and blood sugar control.</p>

                <p class="text-gray-600 mb-6">The main goal of bariatric surgery is weight loss, but it also helps improve obesity-related conditions such as:</p>

                <ul class="list-disc list-inside text-gray-600 mb-6 space-y-2">
