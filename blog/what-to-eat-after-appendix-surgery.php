                        Phase 3: Days 4 to 7 &ndash; Soft Solids &amp; Lean Protein
                    </h3>
                    <p class="mb-2 text-sm text-gray-700">
                        As your appetite normalizes, add soft solid foods. Lean protein is critical at this stage to build collagen and repair surgical tissue.
                    </p>
                    <div class="grid grid-cols-1 md:grid-cols-2 gap-3 text-xs">
                        <div class="bg-blue-50/60 p-3 rounded-lg">
