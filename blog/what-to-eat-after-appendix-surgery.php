                        <span class="w-7 h-7 rounded-full bg-blue-100 text-scod flex items-center justify-center font-bold text-xs">1</span>
                        Phase 1: Day 1 (0 to 24 Hours) &ndash; Clear Liquids &amp; Gut Rest
                    </h3>
                    <p class="mb-2 text-sm text-gray-700">
                        In the first 24 hours, your gut recovers from anesthesia. Once your care team confirms bowel sounds and you pass flatus, take small sips of clear fluids to restore hydration.
                    </p>
