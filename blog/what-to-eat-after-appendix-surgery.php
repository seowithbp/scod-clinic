                        <div class="bg-blue-50/60 p-3 rounded-lg">
                            <span class="font-bold text-gray-900">Recommended:</span> Plain warm water, electrolyte solution, clear broth, coconut water, chamomile tea.
                        </div>
                        <div class="bg-red-50/60 p-3 rounded-lg">
                            <span class="font-bold text-gray-900">Avoid:</span> Milk, creamy drinks, fizzy sodas, citrus juices, and solid snacks.
                        </div>
                    </div>
