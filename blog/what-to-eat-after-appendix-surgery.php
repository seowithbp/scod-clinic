                        Phase 2: Days 2 to 3 &ndash; Full Liquids &amp; Smooth Purees
                    </h3>
                    <p class="mb-2 text-sm text-gray-700">
                        Once liquids are tolerated, transition to smooth purees and light semi-solids that provide clean energy and protein without burdening digestion.
                    </p>
                    <div class="grid grid-cols-1 md:grid-cols-2 gap-3 text-xs">
                        <div class="bg-blue-50/60 p-3 rounded-lg">
                            <span class="font-bold text-gray-900">Recommended:</span> Moong dal water, runny khichdi, probiotic curd (dahi), smooth applesauce, blended lauki or pumpkin soup.
                        </div>
                        <div class="bg-red-50/60 p-3 rounded-lg">
                            <span class="font-bold text-gray-900">Avoid:</span> Heavy spices, whole beans (rajma, chana), raw onions, and buttery gravies.
