                <h2 class="text-2xl md:text-3xl font-bold text-gray-900 mt-10 mb-4">Foods to Avoid After Appendix Surgery</h2>
                <p class="mb-3">
                    Avoiding problematic foods during the first 2 to 3 weeks prevents severe cramps, gas, and digestive discomfort:
                </p>
                <ul class="list-disc list-inside space-y-2 mb-8 pl-2 text-gray-700">
                    <li><strong>Deep-Fried &amp; Fatty Foods:</strong> Samosas, pakoras, French fries, and oily curries slow digestion and trigger nausea.</li>
                    <li><strong>Spicy Foods &amp; Chilies:</strong> Hot spices irritate sensitive stomach linings and can cause heartburn and cramps.</li>
                    <li><strong>Gas-Forming Vegetables:</strong> Cabbage, cauliflower, broccoli, raw onions, radishes, and kidney beans cause severe bloating.</li>
                    <li><strong>Carbonated Beverages:</strong> Sodas and fizzy drinks introduce swallowed gas, worsening abdominal fullness.</li>
                    <li><strong>Tough Red Meat:</strong> Mutton and processed meats take long to digest and aggravate constipation.</li>
                    <li><strong>Alcohol &amp; Heavy Caffeine:</strong> Alcohol interferes with medications and slows wound healing, while excess coffee causes dehydration.</li>
                </ul>

