                <h2 class="text-2xl font-bold text-gray-900 mt-8 mb-4">Managing Digestive Side Effects While Gaining Weight</h2>
                <p class="mb-6 font-semibold text-gray-800 bg-blue-50 border-l-4 border-scod p-4 rounded-r-xl">Managing side effects requires monitoring stool consistency, maintaining hydration, and considering targeted digestive enzymes under medical supervision.</p>

                <p class="mb-6">As you increase your daily calories, monitor how your digestive system responds. If you experience sudden diarrhea, abdominal cramping, or gas bloating, take the following corrective steps:</p>

                <ul class="list-disc list-inside mb-6 space-y-2 text-gray-600">
                    <li><strong>Scale Back Fat Portions:</strong> If stool becomes loose, temporarily reduce your fat intake for 2 to 3 days and rely more on complex carbohydrates like rice and oats for calories.</li>
                    <li><strong>Hydrate Between Meals:</strong> Avoid drinking large glasses of water during meals, as this dilutes stomach acid and digestive enzymes. Drink fluids 30 minutes before or after eating.</li>
                    <li><strong>Consider Ox Bile or Lipase Supplements:</strong> For patients with persistent fat malabsorption, over-the-counter or prescription digestive enzymes containing lipase and ox bile can assist in fat emulsification. Always consult your doctor at SCOD Clinic before starting any supplement regimen.</li>
                </ul>

                <h2 class="text-2xl font-bold text-gray-900 mt-8 mb-4">When to Consult Your Surgeon</h2>
                <p class="mb-6 font-semibold text-gray-800 bg-blue-50 border-l-4 border-scod p-4 rounded-r-xl">Unintentional, rapid weight loss accompanied by severe abdominal pain, jaundice, or chronic diarrhea requires immediate medical evaluation by a specialist.</p>

                <p class="mb-6">While mild weight fluctuation is expected after cholecystectomy, persistent weight loss should not be ignored. Contact your surgical team if you experience any of the following red flag symptoms:</p>

                <ul class="list-disc list-inside mb-6 space-y-2 text-gray-600">
                    <li>Unexplained weight loss exceeding 5% of your total body weight within a month.</li>
                    <li>Severe, unrelenting diarrhea lasting longer than 4 weeks post-surgery.</li>
                    <li>Yellowing of the skin or eyes (jaundice), dark urine, or pale clay-colored stools.</li>
                    <li>Persistent abdominal pain, fever, chills, or nausea.</li>
                </ul>

