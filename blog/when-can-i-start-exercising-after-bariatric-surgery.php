                <section id="protecting-incisions-preventing-hernias" class="space-y-4">
                    <h2 class="text-2xl md:text-3xl font-extrabold text-gray-900 tracking-tight">Protecting Healing Incisions and Avoiding Incisional Hernias</h2>
                    <p>
                        The medical reason behind the strict 6-week lifting limit involves fascial healing. Keyhole surgery creates small punctures through skin, fat, and abdominal wall fascia.
                    </p>
                    <p>
                        While skin surfaces seal within two weeks, deep fascia requires 6 to 8 weeks to regain adequate strength. Straining with heavy loads or aggressive abdominal crunches spikes intra-abdominal pressure. This tension can push internal tissue through a healing puncture, creating an incisional hernia that may require surgical repair.
                    </p>
                    <p>
                        To safeguard your healing incisions:
                    </p>
                    <ul class="list-disc pl-6 space-y-2">
                        <li>Observe the 5-kg lifting limit strictly during the first six weeks.</li>
                        <li>Never hold your breath during physical effort; exhale on exertion and inhale on release.</li>
                        <li>Place a soft pillow against your abdomen when coughing or sneezing in early weeks.</li>
                        <li>Inspect port incisions regularly for unusual swelling, redness, or tenderness.</li>
                    </ul>
                </section>

                <section id="nutritional-rules-for-exercise" class="space-y-4">
                    <h2 class="text-2xl md:text-3xl font-extrabold text-gray-900 tracking-tight">Critical Fueling Guidelines: Hydration and Protein Intake</h2>
                    <p>
                        Working out after bariatric surgery requires mindful hydration and nutrition. With a smaller stomach volume, your fueling habits must adapt:
                    </p>
                    <div class="space-y-4 my-6">
                        <div class="bg-gray-50 p-5 rounded-2xl border border-gray-100">
                            <h3 class="font-bold text-gray-900 text-base mb-1">Continuous Water Sips</h3>
                            <p class="text-sm text-gray-600">Never wait until thirst strikes. Chugging water can trigger nausea. Take small sips every few minutes throughout the day, aiming for 1.5 to 2.0 liters daily.</p>
                        </div>
                        <div class="bg-gray-50 p-5 rounded-2xl border border-gray-100">
                            <h3 class="font-bold text-gray-900 text-base mb-1">Prioritize High-Quality Protein</h3>
                            <p class="text-sm text-gray-600">Active muscles require amino acids. Aim for 60 to 80 grams of daily protein from whey isolate shakes, eggs, paneer, and soft fish, having a protein snack within an hour post-workout.</p>
                        </div>
                        <div class="bg-gray-50 p-5 rounded-2xl border border-gray-100">
                            <h3 class="font-bold text-gray-900 text-base mb-1">Separate Fluids and Meals</h3>
                            <p class="text-sm text-gray-600">Avoid drinking fluids while eating or within 30 minutes before and after meals to prevent dumping symptoms.</p>
                        </div>
                        <div class="bg-gray-50 p-5 rounded-2xl border border-gray-100">
                            <h3 class="font-bold text-gray-900 text-base mb-1">Electrolyte Replenishment</h3>
