                    <h2 class="text-2xl md:text-3xl font-extrabold text-gray-900 tracking-tight">Common Exercise Mistakes to Avoid Post-Surgery</h2>
                    <p>
                        While motivation is positive, overexertion can lead to fatigue or injury. Be mindful of these common missteps:
                    </p>
                    <ul class="list-disc pl-6 space-y-2">
                        <li>Comparing your recovery speed to others who began with different fitness levels.</li>
                        <li>Skipping planned rest days, which are essential for muscle repair on a reduced-calorie diet.</li>
                        <li>Relying solely on cardio while neglecting resistance training, which preserves lean muscle.</li>
                        <li>Pushing through sharp abdominal discomfort; soreness in limbs is expected, but abdominal pain demands prompt review.</li>
                        <li>Missing daily bariatric vitamins, which provide the iron, calcium, and B-vitamins your body needs.</li>
                    </ul>
