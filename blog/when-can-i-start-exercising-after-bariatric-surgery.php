                <section id="understanding-movement-timeline" class="space-y-4">
                    <h2 class="text-2xl md:text-3xl font-extrabold text-gray-900 tracking-tight">Role of Physical Activity After Weight Loss Surgery</h2>
                    <p>
                        Undergoing weight loss surgery is a transformative milestone toward lasting health. When exploring <a href="https://scodclinic.com/services/bariatric-surgery" class="text-scod font-semibold hover:underline">Bariatric Surgery in Delhi</a>, patients naturally focus on dietary adjustments and initial scale victories. Yet purposeful physical activity after weight loss surgery is just as vital for preserving lean body mass, accelerating energy metabolism, and ensuring lasting results.
                    </p>
                    <p>
                        A common misconception is that patients need to engage in high-intensity gym workouts or heavy weightlifting immediately. In truth, recovery is a gradual journey. Rushing into strenuous activity prematurely risks straining internal healing tissue, whereas staying completely sedentary can slow your metabolic rate boost and lead to muscle loss. Following a structured roadmap allows you to build cardiovascular endurance and protect healing incisions safely.
                    </p>
                    <p>
                        Leading bariatric surgeon <a href="https://scodclinic.com/about" class="text-scod font-semibold hover:underline">Dr. Arush Sabharwal</a> stresses that movement after surgery serves three main goals: maintaining functional muscle mass, increasing daily energy expenditure, and restoring joint flexibility. Let us review the timeline recommended by surgical specialists so you can resume active living safely.
                    </p>
                </section>

                <section id="immediate-post-op-walking" class="space-y-4">
                    <h2 class="text-2xl md:text-3xl font-extrabold text-gray-900 tracking-tight">Days 1 to 14: Early Ambulation and Gentle Walking</h2>
                    <p>
                        Your exercise journey begins earlier than you might anticipate. After laparoscopic surgery, clinical staff will assist you in standing up and walking down hospital corridors within 3 to 4 hours of leaving the recovery room.
                    </p>
                    <p>
                        Why is walking after bariatric surgery prioritized so early? Walking stimulates circulation in the lower extremities, substantially reducing the risk of deep vein thrombosis (DVT). Movement also stimulates bowel motility, helping eliminate residual carbon dioxide gas used during laparoscopy to ease abdominal pressure.
                    </p>
                    <p>
                        During your initial two weeks at home, keep movement gentle and consistent:
                    </p>
                    <ul class="list-disc pl-6 space-y-2">
                        <li>Take short, frequent strolls lasting 5 to 10 minutes, 3 to 4 times a day.</li>
                        <li>Walk on flat, level surfaces indoors or outside, avoiding steep paths and stairs.</li>
                        <li>Keep your hands free without carrying bags or weighted personal items.</li>
                        <li>Stop and rest immediately if you experience dizziness or shortness of breath.</li>
                    </ul>
                    <p>
                        In these opening two weeks, your primary goal is gentle circulation, not heavy calorie burning. Gentle walking protects your health without placing physical stress on your foundational <a href="/blog/what-is-done-in-bariatric-surgery" class="text-scod font-semibold hover:underline">bariatric surgery recovery process</a>.
                    </p>
                </section>

                <section id="weeks-3-to-4-cardio" class="space-y-4">
                    <h2 class="text-2xl md:text-3xl font-extrabold text-gray-900 tracking-tight">Weeks 3 to 4: Introducing Low-Impact Aerobic Training</h2>
                    <p>
                        By the third week, skin incisions are well healed, and daily stamina improves on pureed or soft foods. You can now introduce low-impact aerobic training:
                    </p>
                    <div class="grid grid-cols-1 md:grid-cols-2 gap-4 my-6">
                        <div class="bg-blue-50/50 p-5 rounded-2xl border border-blue-100">
                            <h3 class="text-lg font-bold text-gray-900 mb-2">Brisk Walking</h3>
                            <p class="text-sm text-gray-600">Walk for 20 to 30 continuous minutes at a conversational pace without breathlessness.</p>
                        </div>
                        <div class="bg-blue-50/50 p-5 rounded-2xl border border-blue-100">
                            <h3 class="text-lg font-bold text-gray-900 mb-2">Stationary Recumbent Bike</h3>
                            <p class="text-sm text-gray-600">A recumbent bike protects knees and hips while keeping core muscles relaxed in a supportive seat.</p>
                        </div>
                        <div class="bg-blue-50/50 p-5 rounded-2xl border border-blue-100">
                            <h3 class="text-lg font-bold text-gray-900 mb-2">Elliptical Cross-Trainer</h3>
                            <p class="text-sm text-gray-600">Elliptical machines provide steady aerobic conditioning without joint pounding on hard surfaces.</p>
                        </div>
                        <div class="bg-blue-50/50 p-5 rounded-2xl border border-blue-100">
                            <h3 class="text-lg font-bold text-gray-900 mb-2">Gentle Mobility Work</h3>
                            <p class="text-sm text-gray-600">Neck, shoulder, and ankle mobility stretches ease joint stiffness after surgical downtime.</p>
                        </div>
                    </div>
                    <p>
                        Regular aerobic movement aids blood sugar regulation, which is especially beneficial for patients focused on <a href="/blog/can-bariatric-surgery-reverse-diabetes" class="text-scod font-semibold hover:underline">reversing chronic metabolic conditions</a> like type 2 diabetes. However, swimming and weights over 5 kg remain off-limits.
                    </p>
                </section>

                <section id="weeks-5-to-6-resistance" class="space-y-4">
                    <h2 class="text-2xl md:text-3xl font-extrabold text-gray-900 tracking-tight">Weeks 5 to 6: Light Resistance Bands and Mobility Work</h2>
                    <p>
                        Entering month two, rapid fat loss is active. Without muscle stimulation, the body can burn both fat and skeletal muscle. Adding resistance and strength training under clinical supervision is essential for muscle mass preservation and metabolic defense.
                    </p>
                    <p>
                        Global <a href="https://en.wikipedia.org/wiki/Physical_exercise" target="_blank" rel="noopener noreferrer" class="text-scod font-semibold hover:underline">aerobic physical exercise</a> guidelines show that resistance training improves insulin sensitivity and bone density. In weeks 5 and 6, you can safely introduce light resistance:
                    </p>
                    <ul class="list-disc pl-6 space-y-2">
                        <li>Elastic resistance bands for seated leg presses, arm curls, and chest pulls.</li>
                        <li>Bodyweight mini-squats using a sturdy chair for balance.</li>
                        <li>Light hand weights of 1 to 2 kg for seated arm raises.</li>
                        <li>Low platform step-ups to build quad strength safely.</li>
                    </ul>
                    <p>
                        Keep sessions around 30 minutes, resting on alternate days. Combining light resistance with protein is also helpful for patients focused on <a href="/blog/how-to-stop-hair-loss-after-bariatric-surgery" class="text-scod font-semibold hover:underline">preventing nutritional hair loss</a> while losing weight rapidly.
                    </p>
                </section>

                <section id="weeks-7-and-beyond-full-workouts" class="space-y-4">
                    <h2 class="text-2xl md:text-3xl font-extrabold text-gray-900 tracking-tight">Weeks 7 to 8 and Beyond: Gym Workouts, Swimming, and Core</h2>
                    <p>
                        Reaching weeks 7 and 8 is a major milestone. Deep muscle fascia has regained substantial tensile strength. Following your clinical review and surgeon clearance guidelines, most workout limitations are lifted:
                    </p>
                    <div class="space-y-4 my-6">
                        <div class="p-5 bg-white rounded-2xl border border-gray-200 shadow-sm">
                            <h3 class="text-lg font-bold text-gray-900 mb-2">Swimming and Water Aerobics</h3>
                            <p class="text-sm text-gray-600">Once your surgeon confirms all port incisions are fully closed, you can start lap swimming and low-impact water aerobics. Water supports joint weight while offering natural resistance.</p>
                        </div>
                        <div class="p-5 bg-white rounded-2xl border border-gray-200 shadow-sm">
                            <h3 class="text-lg font-bold text-gray-900 mb-2">Gym Resistance Machines</h3>
                            <p class="text-sm text-gray-600">Progress to cable systems and gym machines. Lat pulldowns, seated chest presses, and leg curls activate major muscle groups to sustain daily resting metabolism.</p>
                        </div>
                        <div class="p-5 bg-white rounded-2xl border border-gray-200 shadow-sm">
                            <h3 class="text-lg font-bold text-gray-900 mb-2">Gradual Core Strengthening</h3>
                            <p class="text-sm text-gray-600">Introduce gentle core exercises like modified knee planks and pelvic bridges. Strengthening your trunk improves posture as your body weight decreases.</p>
                        </div>
                    </div>
                    <p>
                        Track stamina and joint ease rather than watching the scale alone. Mindfully <a href="/blog/how-much-weight-loss-after-bariatric-surgery" class="text-scod font-semibold hover:underline">tracking your weight loss</a> alongside fitness milestones provides lasting encouragement.
                    </p>
                </section>

