                <h2 id="defining-obesity" class="text-2xl md:text-3xl font-bold text-gray-900 mt-10 mb-4 pt-4 border-t border-gray-100">
                    Defining Obesity: A Chronic Disease, Not a Cosmetic Flaw
                </h2>

                <p>
                    Obesity is formally defined by the World Health Organization as abnormal or excessive fat accumulation that poses significant health risks. While clinical assessments rely on Body Mass Index (BMI) to measure general categories, the true danger lies in how adipose tissue disrupts biological equilibrium.
                </p>

                <p>
                    Human genetics evolved in eras of food scarcity, developing potent biological mechanisms to conserve energy and defend against starvation. In our current environment of sedentary lifestyles and hyper-palatable foods, these survival mechanisms backfire. Once chronic adiposity takes root, the body’s metabolic set-point shifts upward, actively fighting caloric restriction by increasing hunger hormones and dropping resting energy expenditure.
                </p>

