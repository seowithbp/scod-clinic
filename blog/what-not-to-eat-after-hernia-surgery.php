                <h2 class="text-2xl font-bold text-gray-900 mt-8 mb-4">Phase-by-Phase Recovery Diet Timeline</h2>
                <div class="mb-6 font-semibold text-gray-800 bg-blue-50 border-l-4 border-scod p-4 rounded-r-xl">
                    <p><strong>Stepwise Progression:</strong> Day 1 (Clear Liquids) &rarr; Days 2–4 (Full Liquids & Purees) &rarr; Days 5–14 (Soft, Gentle Soluble-Fiber Foods) &rarr; Week 3+ (Careful Transition to Regular Diet).</p>
