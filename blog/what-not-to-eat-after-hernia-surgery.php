                <h2 class="text-2xl font-bold text-gray-900 mt-8 mb-4">Why Diet Matters: Understanding Intra-Abdominal Pressure</h2>
                <div class="mb-6 font-semibold text-gray-800 bg-blue-50 border-l-4 border-scod p-4 rounded-r-xl">
                    <p><strong>Clinical Fact:</strong> During modern <a href="https://en.wikipedia.org/wiki/Hernia_repair" target="_blank" rel="noopener noreferrer" class="text-scod hover:text-blue-700 font-semibold underline">hernia repair</a>, synthetic surgical mesh reinforces weakened muscle tissue. Until natural collagen incorporates into the mesh over 6 to 8 weeks, pressure surges from bowel straining or trapped gas can pull on fresh sutures.</p>
                </div>

                <p class="mb-6">The abdomen functions like a closed cylinder. Volume increases from intestinal gas, stool impaction, or muscular pushing elevate <strong>intra-abdominal pressure (IAP)</strong>. Consuming the wrong foods triggers three distinct surgical risks:</p>

                <ul class="list-disc list-inside mb-6 space-y-3 text-gray-600">
                    <li><strong>Bowel Straining:</strong> Pain relievers and anesthesia slow digestive peristalsis. Constipating foods make stool dry and hard. Pushing forcefully spikes intra-abdominal pressure up to 200 mmHg, risking suture disruption and mesh displacement.</li>
                    <li><strong>Intestinal Gas Distension:</strong> Fermentable carbs and fizzy drinks generate high gas volumes, stretching abdominal muscles from inside. If you notice swelling, understand common causes of <a href="/blog/why-is-my-stomach-bigger-after-hernia-surgery" class="text-scod hover:text-blue-700 font-semibold">post-surgical stomach swelling</a> to distinguish normal post-op edema from gas bloating.</li>
                    <li><strong>Vomiting Reflex:</strong> Greasy or heavily spiced meals irritate the stomach lining, triggering acute nausea or vomiting. Violent contractions during retching place intense mechanical strain on incision lines.</li>
                </ul>

                <h2 class="text-2xl font-bold text-gray-900 mt-8 mb-4">Primary List: Food Not to Eat after Hernia Surgery</h2>
                <p class="mb-6 font-semibold text-gray-800 bg-blue-50 border-l-4 border-scod p-4 rounded-r-xl">Eliminate these 8 food and beverage categories during your first 2 to 3 weeks of recovery to protect your surgical repair.</p>

