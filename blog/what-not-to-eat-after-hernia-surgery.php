                <h3 class="text-xl font-semibold text-gray-900 mt-6 mb-3">Days 1 to 2: Clear Fluids & Gut Rest</h3>
                <p class="mb-4">Right after surgery, digestive motility is sluggish. Consume small sips of room-temperature fluids: plain water, electrolyte drinks, light vegetable or chicken broth, and warm chamomile tea. As bowel sounds return and you pass gas, introduce pureed soups and smooth plain yogurt.</p>

                <h3 class="text-xl font-semibold text-gray-900 mt-6 mb-3">Days 3 to 7: Soft, Protein-Rich Meals</h3>
                <p class="mb-4">Progress to soft solid foods that require minimal digestive effort: soft scrambled eggs, mashed sweet potatoes, steamed white fish, ripe bananas, applesauce, and mild khichdi. Drink 2 to 3 liters of fluids daily to keep stools soft.</p>

                <h3 class="text-xl font-semibold text-gray-900 mt-6 mb-3">Days 8 to 21: Gradual Fiber Introduction</h3>
                <p class="mb-4">Introduce well-cooked vegetables (carrots, peeled zucchini) and soft oatmeal. Continue avoiding raw cruciferous vegetables, greasy takeout, and fizzy drinks until your clinical follow-up examination.</p>

                <h3 class="text-xl font-semibold text-gray-900 mt-6 mb-3">Week 3 Onward: Long-Term Nutrition</h3>
                <p class="mb-4">Most patients can resume a balanced diet by the third or fourth week. If you have questions about alternatives, learn about <a href="/blog/can-hernia-be-cured-without-surgery" class="text-scod hover:text-blue-700 font-semibold">non-surgical hernia management</a>. Maintaining long-term digestive health protects against complications; read more about <a href="/blog/does-hernia-come-back-after-surgery" class="text-scod hover:text-blue-700 font-semibold">hernia recurrence risks</a>.</p>

                <h2 class="text-2xl font-bold text-gray-900 mt-8 mb-4">Managing Constipation Without Straining</h2>
                <p class="mb-6">If 48 to 72 hours pass without a bowel movement, <strong>do not sit and strain</strong>. Follow these safe steps to encourage gentle elimination:</p>

                <ol class="list-decimal list-inside mb-6 space-y-3 text-gray-600 font-medium">
                    <li><span class="text-gray-800 font-semibold">Drink Warm Fluids in the Morning:</span> A glass of warm water or prune juice on an empty stomach stimulates the gastrocolic reflex naturally.</li>
                    <li><span class="text-gray-800 font-semibold">Take Gentle Hallway Walks:</span> Light, slow 5- to 10-minute walks encourage intestinal contractions without stressing incisions.</li>
                    <li><span class="text-gray-800 font-semibold">Elevate Your Feet on a Stool:</span> Raising your knees slightly above hip level straightens the anorectal angle, allowing stool to pass smoothly without pushing.</li>
                    <li><span class="text-gray-800 font-semibold">Consult Your Doctor for Stool Softeners:</span> Never take harsh stimulant laxatives without medical advice. Your surgeon can prescribe gentle osmotic softeners such as lactulose.</li>
                </ol>

