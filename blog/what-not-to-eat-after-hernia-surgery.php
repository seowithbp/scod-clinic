                        <h3 class="text-xl font-bold text-gray-900 mb-2 flex items-center gap-2">
                            <i data-feather="slash" class="w-5 h-5 text-red-500"></i>
                            1. Carbonated Beverages and Fizzy Drinks
                        </h3>
                        <p class="text-gray-600">Sodas, sparkling water, and beer contain dissolved carbon dioxide gas under pressure. When ingested, this gas expands rapidly in your stomach, causing acute bloating, painful belching, and pressure against abdominal incisions. Abstain from all fizzy drinks for at least 3 weeks.</p>
                    </div>

                    <!-- Item 2 -->
                    <div class="bg-gray-50 p-6 rounded-2xl border border-gray-200">
                        <h3 class="text-xl font-bold text-gray-900 mb-2 flex items-center gap-2">
                            <i data-feather="slash" class="w-5 h-5 text-red-500"></i>
                            2. Gas-Forming Vegetables and Whole Legumes
                        </h3>
                        <p class="text-gray-600">Raw cruciferous vegetables (cabbage, cauliflower, broccoli, kale) and dried legumes (kidney beans, chickpeas, black lentils) contain complex oligosaccharides like raffinose. Digesting raffinose requires heavy bacterial fermentation in the colon, triggering gas and painful cramping. For general dietary guidance, follow our <a href="/blog/what-to-eat-after-laparoscopic-surgery" class="text-scod hover:text-blue-700 font-semibold">laparoscopic diet guide</a>.</p>
                    </div>

                    <!-- Item 3 -->
                    <div class="bg-gray-50 p-6 rounded-2xl border border-gray-200">
                        <h3 class="text-xl font-bold text-gray-900 mb-2 flex items-center gap-2">
                            <i data-feather="slash" class="w-5 h-5 text-red-500"></i>
                            3. Deep-Fried, Greasy, and High-Fat Fast Foods
                        </h3>
                        <p class="text-gray-600">Deep-fried snacks (samosas, pakoras, french fries, burgers, and oily curries) significantly delay gastric emptying. Food stays in the stomach much longer, causing severe nausea, acid regurgitation, and heavy sluggishness. These foods lack water-soluble fiber and worsen constipation.</p>
                    </div>

                    <!-- Item 4 -->
                    <div class="bg-gray-50 p-6 rounded-2xl border border-gray-200">
                        <h3 class="text-xl font-bold text-gray-900 mb-2 flex items-center gap-2">
                            <i data-feather="slash" class="w-5 h-5 text-red-500"></i>
                            4. Refined Carbohydrates & Constipating Processed Foods
                        </h3>
                        <p class="text-gray-600">White bread, maida flour, pastries, and processed snacks lack dietary fiber. Inside sluggish post-op intestines, they form hard stools requiring forceful straining.</p>
                    </div>

                    <!-- Item 5 -->
                    <div class="bg-gray-50 p-6 rounded-2xl border border-gray-200">
                        <h3 class="text-xl font-bold text-gray-900 mb-2 flex items-center gap-2">
                            <i data-feather="slash" class="w-5 h-5 text-red-500"></i>
                            5. Hot Chili, Pungent Spices, and Acidic Condiments
                        </h3>
                        <p class="text-gray-600">Chili powders, hot peppers, and vinegars irritate the stomach lining, triggering reflux and heartburn. Spices can also provoke coughing spasms, which spike intra-abdominal pressure.</p>
                    </div>

                    <!-- Item 6 -->
                    <div class="bg-gray-50 p-6 rounded-2xl border border-gray-200">
                        <h3 class="text-xl font-bold text-gray-900 mb-2 flex items-center gap-2">
                            <i data-feather="slash" class="w-5 h-5 text-red-500"></i>
                            6. Aged Cheeses and Dense Dairy Products
                        </h3>
                        <p class="text-gray-600">Hard aged cheeses, rich cream, and heavy butter are known binding foods that slow digestion. When combined with prescription pain relievers, they frequently trigger severe constipation. Choose light probiotic yogurt or fresh cottage cheese (paneer) in moderation instead.</p>
                    </div>

                    <!-- Item 7 -->
                    <div class="bg-gray-50 p-6 rounded-2xl border border-gray-200">
                        <h3 class="text-xl font-bold text-gray-900 mb-2 flex items-center gap-2">
                            <i data-feather="slash" class="w-5 h-5 text-red-500"></i>
                            7. Alcohol and Excessive Caffeine
                        </h3>
                        <p class="text-gray-600">Alcohol impairs tissue collagen synthesis, thins the blood, suppresses immune defenses, and interacts dangerously with pain medications. Strong coffee and energy drinks act as diuretics that dehydrate stools. Avoid alcohol completely for at least 2 to 3 weeks.</p>
                    </div>

