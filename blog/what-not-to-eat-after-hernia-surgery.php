                        <h3 class="text-xl font-bold text-gray-900 mb-2 flex items-center gap-2">
                            <i data-feather="slash" class="w-5 h-5 text-red-500"></i>
                            8. Tough Red Meat and Chewy Processed Meats
                        </h3>
                        <p class="text-gray-600">Red and cured meats (beef, mutton, sausages) require heavy digestive effort. When resting post-surgery, they sit stagnant in the stomach. Choose tender chicken, scrambled eggs, or soft lentils instead.</p>
