                    <p class="text-sm font-semibold text-scod uppercase tracking-wide mb-1">Quick Answer (AEO Summary)</p>
                    <p class="text-gray-800 text-base leading-relaxed m-0">
                        <strong>What is the normal size of appendix?</strong> In healthy adults, the normal human appendix measures between <strong>6 and 9 cm in length</strong> and has an outer diameter of <strong>6 mm or less</strong> (averaging 4 to 6 mm). The wall thickness is normally under <strong>2 to 3 mm</strong>. An outer diameter measuring <strong>7 mm or greater</strong> on ultrasound or CT scan, particularly accompanied by wall thickening and tenderness, indicates inflammation and strongly points to acute appendicitis.
