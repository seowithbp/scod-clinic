                <h2 class="text-2xl md:text-3xl font-bold text-gray-900 mt-10 mb-4">Understanding How Gastric Bypass Works: The Dual Action Power</h2>
                <p class="mb-4">
                    To appreciate why gastric bypass outperforms other procedures, you must understand how it alters your digestive anatomy. Most weight loss procedures rely entirely on restriction: they shrink the size of your stomach so you feel physically full after eating small portions. Gastric bypass, however, utilizes a powerful <strong>dual mechanism</strong>:
                </p>
                <ul class="list-disc list-inside space-y-2 mb-6 pl-2 text-gray-700">
                    <li>
                        <strong>Component 1: Physical Restriction:</strong> The surgeon divides the upper stomach to form an egg-sized pouch holding only 30 milliliters (about one ounce) of food. This immediately limits how much you can eat in a single sitting, bringing rapid satiety.
                    </li>
                    <li>
                        <strong>Component 2: Caloric &amp; Nutrient Malabsorption:</strong> The surgeon connects this new pouch directly to the middle section of the small intestine (the jejunum), bypassing the rest of the stomach and the duodenum (the first part of the small intestine). This shortens the digestive tract where calorie and carbohydrate absorption normally happens.
                    </li>
                </ul>
