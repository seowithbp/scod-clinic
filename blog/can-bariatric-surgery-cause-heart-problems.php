                <h2 class="text-2xl font-bold text-gray-900 mt-10 mb-4">The Big Picture: How Bariatric Surgery Protects Your Heart</h2>
                <p class="leading-relaxed">
                    To understand whether weight loss procedures pose a cardiac risk, we must first look at the severe toll chronic obesity takes on the human heart. Excess body mass forces the heart to work significantly harder to supply blood to enlarged tissue networks. Over time, this chronic strain leads to arterial stiffness, high blood pressure, coronary artery disease, and eventual heart failure.
                </p>

                <p class="leading-relaxed">
                    When patients undergo procedures like Laparoscopic Sleeve Gastrectomy (gastric sleeve) or Roux-en-Y Gastric Bypass, the resulting weight loss provides immediate relief to the cardiovascular system. The <strong>cardiovascular benefits of bariatric surgery</strong> are swift and long-lasting:
                </p>

                <ul class="list-disc list-inside space-y-3 pl-4 bg-gray-50 p-6 rounded-xl border border-gray-100">
                    <li><strong>Hypertension Remission:</strong> Over 70% of patients experience significant drops in blood pressure within weeks of surgery, often reducing or completely eliminating their reliance on anti-hypertensive medications.</li>
                    <li><strong>Reduced Risk of Heart Attack and Stroke:</strong> Long-term clinical studies demonstrate a 40% to 50% decrease in major adverse cardiovascular events (MACE) among post-bariatric patients compared to non-surgical weight management groups.</li>
                    <li><strong>Reversal of Cardiac Enlargement:</strong> Left ventricular hypertrophy (thickening of the heart muscle caused by overwork) frequently improves as the cardiac workload drops following weight loss.</li>
                    <li><strong>Improved Lipid Profiles:</strong> Surgery dramatically lowers harmful LDL cholesterol and triglycerides while raising beneficial HDL cholesterol levels.</li>
                    <li><strong>Bariatric Surgery for Heart Failure Patients:</strong> Controlled weight loss can significantly improve heart ejection fraction (pumping efficiency) in individuals suffering from obesity-induced heart failure.</li>
                </ul>

