                <h2 class="text-2xl font-bold text-gray-900 mt-10 mb-4">Understanding Potential Heart-Related Side Effects Post-Surgery</h2>
                <p class="leading-relaxed">
                    While the <strong>long-term heart risk after bariatric procedure</strong> is significantly lower than remaining severely obese, patients may occasionally experience short-term cardiac sensations during recovery. It is important to distinguish between benign adaptation symptoms and conditions that require medical attention.
                </p>

                <h3 class="text-xl font-semibold text-gray-900 mt-6 mb-3">1. Post-Bariatric Surgery Heart Palpitations & Rapid Heart Rate</h3>
                <p class="leading-relaxed">
                    One of the most common early recovery complaints is feeling a racing, fluttering, or pounding heart beat. <strong>Post-bariatric surgery heart palpitations</strong> usually stem from non-cardiac root causes:
                </p>
                <ul class="list-disc list-inside space-y-2 pl-4">
                    <li><strong>Dehydration:</strong> Because the stomach capacity is smaller post-op, drinking large amounts of fluid quickly becomes difficult. Reduced fluid intake leads to lower blood volume, causing the heart to beat faster to maintain adequate blood pressure.</li>
                    <li><strong>Electrolyte Imbalance After Weight Loss Surgery:</strong> Rapid weight loss, reduced food intake, or minor post-operative vomiting can deplete key minerals like potassium, magnesium, and sodium. These electrolytes control the electrical impulses of your heart rhythm.</li>
                    <li><strong>Dumping Syndrome:</strong> Consuming simple sugars or refined carbohydrates too quickly after surgery can cause a sudden release of insulin and epinephrine (adrenaline), triggering a temporary surge in heart rate.</li>
                </ul>

                <h3 class="text-xl font-semibold text-gray-900 mt-6 mb-3">2. Heart Rate Changes After Gastric Sleeve or Bypass</h3>
                <p class="leading-relaxed">
                    Noticeable <strong>heart rate changes after gastric sleeve</strong> or bypass are a normal metabolic adjustment. As body mass drops, your resting heart rate typically decreases (a healthy sign of increased cardiovascular efficiency). However, sudden posture changes (sitting to standing) might temporarily cause dizziness or elevated heart rate (orthostatic hypotension) if you are under-hydrated.
                </p>

                <h3 class="text-xl font-semibold text-gray-900 mt-6 mb-3">3. Rare Surgical Complications: Pulmonary Embolism & Stress</h3>
                <p class="leading-relaxed">
                    Like any major abdominal surgery, there are general surgical risks that can secondarily impact the heart if unmanaged:
                </p>
                <ul class="list-disc list-inside space-y-2 pl-4">
                    <li><strong>Pulmonary Embolism Risk After Bariatric Surgery:</strong> A blood clot originating in the deep leg veins (DVT) can travel to the lungs and strain the right side of the heart. Advanced surgical protocols—including early mobilization, blood thinners, and compression stockings—make this risk extremely low (less than 0.5%).</li>
                    <li><strong>Anesthesia & Surgical Stress:</strong> Pre-existing, undiagnosed coronary heart disease can react to surgical stress. This is precisely why thorough pre-operative screening is performed.</li>
                </ul>

