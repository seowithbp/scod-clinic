                    <li><strong>Stress Testing:</strong> Assesses how your heart performs under exercise or simulated physical exertion.</li>
                    <li><strong>Cardiology Consultation:</strong> A specialist cardiologist reviews all reports and optimizes cardiac medications prior to surgery.</li>
