                <!-- Section 8 -->
                <h2 id="long-term-adaptation" class="text-2xl md:text-3xl font-bold text-gray-900 mt-10 mb-4 pt-4 border-t border-gray-100">
                    Post-Surgery Dietary Stages and Supplement Care
                </h2>

                <p>
                    Because gastric bypass alters your gastrointestinal anatomy, your dietary habits progress through distinct phases while tissues heal:
                </p>

                <ul class="list-disc pl-6 space-y-2 text-gray-700">
                    <li>Phase 1 (Week 1): Clear liquids only, focusing on hydration through small sips throughout the day.</li>
                    <li>Phase 2 (Week 2): Full liquids and whey protein isolate shakes to meet 60 to 80 grams of daily protein.</li>
                    <li>Phase 3 (Weeks 3 to 4): Pureed foods such as scrambled eggs, pureed lentils, and soft mashed vegetables.</li>
                    <li>Phase 4 (Month 2 Onward): Healthy solid meals, prioritizing lean protein first, followed by vegetables.</li>
