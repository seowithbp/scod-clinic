                <!-- Section 3 -->
                <h2 id="medical-evaluations" class="text-2xl md:text-3xl font-bold text-gray-900 mt-10 mb-4 pt-4 border-t border-gray-100">
                    Essential Pre-Operative Medical Workup
                </h2>

                <p>
                    Rigorous pre-operative testing ensures total safety during general anesthesia and eliminates unforeseen operative challenges. Standard diagnostic assessments include:
                </p>

                <ul class="list-disc pl-6 space-y-2 text-gray-700">
                    <li>Cardiovascular Clearance: Electrocardiogram (ECG), 2D echocardiography, and stress tests to evaluate cardiac output and rule out silent ischemic heart disease.</li>
                    <li>Pulmonary Evaluation: Chest X-rays and sleep study (polysomnography) if symptoms of obstructive sleep apnea are present.</li>
                    <li>Upper Gastrointestinal Endoscopy: Direct visualization of the esophagus, stomach lining, and duodenum to identify hiatal hernias, gastric ulcers, or active <em>H. pylori</em> bacterial colonization.</li>
                    <li>Comprehensive Laboratory Profile: Fasting blood glucose, HbA1c, liver function tests, kidney profiles, lipid panels, thyroid panels, and baseline vitamin assays (B12, D3, iron, and ferritin).</li>
                    <li>Psychological Evaluation: A supportive assessment ensuring realistic expectations, emotional preparedness, and commitment to lifelong dietary guidelines.</li>
                </ul>

                <!-- Section 4 -->
                <h2 id="insurance-approval" class="text-2xl md:text-3xl font-bold text-gray-900 mt-10 mb-4 pt-4 border-t border-gray-100">
                    Insurance Approval and Financial Coverage
                </h2>

                <p>
                    One of the most frequent concerns patients share is whether health insurance covers gastric bypass surgery. In India and many international jurisdictions, regulatory bodies like the IRDAI have mandated that bariatric surgery must be covered by health insurance policies when performed to treat life-threatening obesity and associated chronic comorbidities, rather than for aesthetic enhancement.
                </p>

                <p>
                    To secure insurance pre-authorization, your surgical team compiles a comprehensive dossier demonstrating:
                </p>

                <ul class="list-disc pl-6 space-y-2 text-gray-700">
                    <li>Confirmed BMI ≥ 40, or BMI ≥ 35 with coexisting conditions such as coronary artery disease, sleep apnea, or severe diabetes.</li>
                    <li>Documented clinical records demonstrating that physician-supervised non-surgical weight loss attempts were unsuccessful.</li>
                    <li>Endocrinologist certification verifying that obesity is not caused by an untreated endocrine disorder (such as untreated hypothyroidism).</li>
                    <li>Clearance letters from cardiology, pulmonology, and psychiatric consultants confirming surgical readiness.</li>
                </ul>

                <!-- Section 5 -->
                <h2 id="liver-reduction-diet" class="text-2xl md:text-3xl font-bold text-gray-900 mt-10 mb-4 pt-4 border-t border-gray-100">
                    The Pre-Surgery Liver Shrinkage Diet
                </h2>

                <p>
                    Approximately 10 to 14 days before your scheduled surgery, you will begin a specialized pre-operative nutrition plan. Many patients wonder why this diet is essential.
                </p>

                <p>
                    In patients carrying chronic excess weight, the left lobe of the liver is typically enlarged with stored fat and glycogen, resting directly over the upper stomach. During laparoscopic surgery, the surgeon must gently elevate the liver to view the gastroesophageal junction. A high-protein, calorie-restricted meal plan rapidly depletes liver glycogen stores, shrinking liver volume by up to 20%. This makes the organ significantly lighter, softer, and less prone to bleeding, ensuring smooth, unobstructed surgical visibility.
                </p>

                <!-- Section 6 -->
                <h2 id="surgery-day-experience" class="text-2xl md:text-3xl font-bold text-gray-900 mt-10 mb-4 pt-4 border-t border-gray-100">
                    What Happens on Surgery Day
                </h2>

                <p>
                    Knowing what to expect inside the surgical unit provides reassurance and peace of mind. To understand the operative steps in detail, you can explore our complete guide on the <a href="/blog/what-is-done-in-bariatric-surgery" class="text-scod hover:text-blue-700 font-semibold underline decoration-scod/40">bariatric surgery procedure</a>.
                </p>

                <p>
                    On surgery morning, you arrive at the hospital fasting. After anesthesia administration and gentle airway protection, the surgical team creates five tiny keyhole incisions measuring between 5 and 12 millimeters. The surgeon divides the upper stomach to form an egg-sized pouch (holding about 30 ml) and reroutes a limb of the small intestine directly to this pouch, allowing digestive enzymes to join food further downstream.
                </p>

                <p>
                    Modern laparoscopic tools and smart motorized staplers ensure clean, microscopic tissue closure. The operation typically concludes within 60 to 90 minutes, with the surgeon performing an intraoperative leak test to verify total integrity before skin closure with dissolvable sutures.
                </p>

