                            </h4>
                            <p class="text-sm text-gray-600">
                                Modern vape pods frequently contain exceptionally high concentrations of nicotine salts, delivering powerful doses of vasoconstrictive chemicals directly into circulation. Even nicotine-free e-liquids contain flavorings and heavy metals that provoke inflammatory reactions.
                            </p>
                        </div>
                        <div class="bg-gray-50 rounded-xl p-5 border border-gray-200">
                            <h4 class="font-bold text-gray-900 mb-2 flex items-center gap-2">
