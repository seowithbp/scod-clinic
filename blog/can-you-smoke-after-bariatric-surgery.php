                            <div class="mt-4 pt-4 border-t border-gray-100 text-gray-600 text-sm md:text-base leading-relaxed">
                                The most dangerous complication is the formation of marginal ulcers at the surgical connection between the stomach pouch and the small intestine. These ulcers are painful, prone to severe bleeding, and can perforate, requiring emergency reoperation.
                            </div>
                        </details>

