                    </p>
                </section>

                <!-- Section 6 -->
                <section id="cardiovascular-and-pulmonary-hazards" class="space-y-4">
                    <h2 class="text-2xl md:text-3xl font-extrabold text-gray-900 tracking-tight">Cardiovascular and Pulmonary Complications Post-Surgery</h2>
                    <p>
                        Smoking introduces serious systemic hazards that extend well beyond the digestive tract, placing heavy stress on both the respiratory and cardiovascular systems during recovery:
                    </p>
                    <ul class="list-disc list-inside space-y-2 pl-2">
                        <li>Deep Vein Thrombosis (DVT) and Pulmonary Embolism (PE): Smoking thickens the blood, accelerates platelet aggregation, and injures blood vessel linings. Following abdominal surgery, smokers are at substantially greater risk of developing dangerous blood clots in the legs that can dislodge to the lungs.</li>
                        <li>Atelectasis and Pneumonia: General anesthesia temporarily suppresses lung expansion. Tobacco smoke paralyses respiratory cilia, leading to mucus plugging, partial lung collapse (atelectasis), and bacterial pneumonia.</li>
                        <li>Cardiovascular Strain: Nicotine elevates resting heart rate and blood pressure, placing undue strain on the heart during surgical recovery. For patients focused on <a href="/blog/can-you-have-bariatric-surgery-after-a-heart-attack" class="text-scod font-semibold hover:underline">protecting long-term cardiovascular health</a>, eliminating tobacco is non-negotiable.</li>
                    </ul>
                </section>

                <!-- Section 7 -->
                <section id="recommended-timeline-for-cessation" class="space-y-4">
                    <h2 class="text-2xl md:text-3xl font-extrabold text-gray-900 tracking-tight">Required Timeline for Smoking Cessation Before and After Surgery</h2>
                    <p>
                        To guarantee safe surgical outcomes, bariatric programs enforce strict timelines for smoking cessation. Adhering to these structured milestones allows your respiratory and circulatory systems to recover critical functionality:
                    </p>
                    <div class="space-y-3 pl-2">
                        <p>
                            Pre-Operative Cessation (Minimum 6 to 8 Weeks): You must stop all smoking and nicotine products at least six to eight weeks before your scheduled operation. Within 48 hours of quitting, carbon monoxide levels in your blood normalize. By six weeks, bronchial ciliary function improves dramatically, and cellular wound healing capabilities rebound toward healthy baselines.
                        </p>
                        <p>
                            Preoperative Cotinine Verification: Many bariatric surgery centers administer a routine urine or blood cotinine screening during preoperative testing. If nicotine metabolites are detected, the surgery is routinely postponed to protect patient safety.
                        </p>
                        <p>
                            Post-Operative Abstinence (Lifelong): The prohibition against smoking does not expire once incisions heal. Resuming smoking six months, one year, or even five years after surgery reignites the risk of marginal ulcers, internal bleeding, and vascular disease.
                        </p>
                    </div>
                </section>

                <!-- Section 8 -->
                <section id="practical-strategies-to-quit-smoking" class="space-y-4">
                    <h2 class="text-2xl md:text-3xl font-extrabold text-gray-900 tracking-tight">Effective Medical Strategies to Quit Smoking Permanently</h2>
                    <p>
                        Overcoming nicotine addiction while preparing for a major metabolic transformation can feel challenging, but you do not have to navigate this transition alone. Proven clinical strategies can help you quit smoking permanently:
                    </p>
                    <ul class="list-disc list-inside space-y-2 pl-2">
                        <li>Prescription Cessation Medications: Non-nicotine oral medications such as bupropion or varenicline can be prescribed by your physician well in advance of surgery to reduce nicotine cravings and withdrawal symptoms without compromising microvascular blood flow.</li>
                        <li>Behavioral Counseling and Support: Working with specialized smoking cessation counselors helps identify psychological triggers, develop healthy stress-coping mechanisms, and build daily accountability.</li>
                        <li>Adopting Healthy Lifestyle Habits: Replacing smoking breaks with brisk walking, hydration, deep breathing exercises, and mindful meditation helps reinforce <a href="/blog/when-can-i-start-exercising-after-bariatric-surgery" class="text-scod font-semibold hover:underline">healthy post-operative lifestyle habits</a> that support lasting wellness.</li>
                        <li>Removing Environmental Triggers: Discard all ashtrays, lighters, cigarette packs, and vaping devices from your home, car, and workspace to create a smoke-free recovery sanctuary.</li>
                    </ul>
                </section>

