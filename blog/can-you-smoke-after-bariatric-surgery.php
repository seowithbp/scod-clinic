                            </h4>
                            <p class="text-sm text-gray-600">
                                While nicotine patches and gums help manage chemical cravings, they continue to circulate nicotine throughout healing stomach tissues. Use of NRT during the perioperative window must be closely coordinated with your surgical team.
                            </p>
