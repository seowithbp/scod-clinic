                        <div>
                            <strong class="text-gray-900">A Visible or Palpable Bulge:</strong>
                            <p class="text-gray-600 text-sm mt-1">The most hallmark sign is a small, soft lump or protrusion near one of the former keyhole scar sites (most commonly around the belly button). This bulge usually becomes more prominent when standing up, coughing, laughing, or straining, and may shrink or disappear when lying flat on your back.</p>
                        </div>
                    </li>
                    <li class="flex items-start gap-3 bg-white p-4 rounded-xl border border-gray-200 shadow-sm">
                        <i data-feather="alert-circle" class="w-5 h-5 text-scod shrink-0 mt-0.5"></i>
                        <div>
                            <strong class="text-gray-900">Localized Discomfort or Aching Pain:</strong>
                            <p class="text-gray-600 text-sm mt-1">Patients often feel a dull ache, tenderness, or a sensation of fullness and heavy dragging pressure at the port site, particularly towards the end of the day or after prolonged standing and physical activity.</p>
                        </div>
                    </li>
                    <li class="flex items-start gap-3 bg-white p-4 rounded-xl border border-gray-200 shadow-sm">
