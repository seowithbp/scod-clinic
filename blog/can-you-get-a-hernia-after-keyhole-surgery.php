                    <p class="text-gray-700 leading-relaxed">
                        Yes, you can get a hernia after keyhole surgery. Medically known as a <em>port-site hernia</em> or trocar-site hernia, it occurs when internal tissues or abdominal organs push through a small muscular defect left behind by one of the surgical keyhole incisions. While the overall incidence is low (ranging between 1% and 3%), factors like larger port sizes, infection, premature physical strain, or poor wound healing increase the risk.
                    </p>
